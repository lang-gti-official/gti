    output << " {\n";
    ++indentation;
    ++classDepth;
    if (stmt.kind() == ClassKind::Interface) {
      writeIndent();
      output << "public:\n";
    }
    for (const StmtPtr &member : stmt.members()) {
      emitClassMember(member);
    }
    emitClassLifecycle(stmt);
    --classDepth;
    --indentation;
    writeIndent();
