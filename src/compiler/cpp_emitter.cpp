  void visitCallExpr(const Call &expr) override {
    if (const ResolvedPayloadConstructionInfo *payload =
            semantics.findPayloadConstruction(expr)) {
      emitSemanticType(SemanticType::enumType(payload->owner));
      output << '{';
      emitSemanticType(SemanticType::enumType(payload->owner));
      output << "::__gti_variant_" << payload->variantIndex << '{';
      emitArguments(expr.arguments());
      output << "}}";
      return;
    }
    if (const DeferredCallableCallInfo *deferred =
            semantics.findDeferredCallableCall(expr);
        deferred != nullptr) {
      output << "::gti_internal::backend::"
             << (deferred->capability == CallableInvocationCapability::Read
                     ? "invoke_read"
                 : deferred->capability == CallableInvocationCapability::Mutable
                     ? "invoke_mutable"
                     : "invoke_once")
             << '(';
      emitExpression(expr.callee());
      output << ", ";
      emitExactCallTag(deferred->capability, deferred->parameterTypes,
                       expr.arguments());
      for (const ExprPtr &argument : expr.arguments()) {
        output << ", ";
        emitExpression(argument);
      }
      output << ')';
      return;
    }
    if (const ResolvedLambdaCallInfo *lambdaCall =
            semantics.findLambdaCall(expr);
        lambdaCall != nullptr && isExplicitMoveCallReceiver(expr.callee())) {
      output << "::gti_internal::backend::invoke_selected(";
      emitExpression(expr.callee());
      output << ", ";
      emitExactCallTag(lambdaCall->capability, lambdaCall->parameterTypes,
                       expr.arguments(), true);
      for (const ExprPtr &argument : expr.arguments()) {
        output << ", ";
        emitExpression(argument);
      }
      output << ')';
      return;
    }
    if (const ResolvedOperatorInfo *operatorCall = semantics.findOperator(expr);
        operatorCall != nullptr &&
        operatorCall->kind == OverloadedOperator::Call) {
      emitOperatorMethodCall(*operatorCall, expr.callee(), expr.arguments());
      return;
    }
    const ResolvedCallInfo *resolved = semantics.findCall(expr);
    if (resolved != nullptr &&
        resolved->intrinsic ==
            IntrinsicKind::DefaultTypeParameterConstruction) {
      emitExpression(expr.callee());
      output << "()";
      return;
    }
    if (resolved != nullptr &&
        (resolved->intrinsic == IntrinsicKind::NumericTypeParameterConversion ||
         resolved->intrinsic == IntrinsicKind::NumericAliasConversion)) {
      output << "::gti_internal::backend::numeric_cast<";
      emitExpression(expr.callee());
      output << ">(";
      emitArguments(expr.arguments());
      output << ')';
      return;
    }
    if (resolved != nullptr &&
        integerArithmeticIntrinsic(resolved->intrinsic)) {
      output << "::gti_internal::backend::"
             << integerArithmeticIntrinsicName(resolved->intrinsic);
      const std::optional<IntegerArithmeticIntrinsic> arithmetic =
          integerArithmeticIntrinsic(resolved->intrinsic);
      if (arithmetic &&
          arithmetic->mode == IntegerArithmeticMode::CheckedResult &&
          resolved->returnType.kind == SemanticType::Expected &&
          resolved->returnType.arguments.size() == 2) {
        output << '<';
        emitSemanticType(resolved->returnType.arguments[1]);
        output << '>';
      }
      output << '(';
      emitArguments(expr.arguments());
      output << ')';
      return;
    }
    if (resolved != nullptr &&
        resolved->intrinsic == IntrinsicKind::AllocateUniqueOwner) {
      output << "::gti_internal::backend::make_unique<";
      if (!expr.typeArguments().empty()) {
        emitType(expr.typeArguments().front());
      }
      output << ">(";
      emitArguments(expr.arguments());
      output << ')';
      return;
    }
    if (resolved != nullptr &&
        (resolved->intrinsic == IntrinsicKind::UniqueOwnerBorrow ||
         resolved->intrinsic == IntrinsicKind::UniqueOwnerBorrowMut)) {
      output << "::gti_internal::backend::owner_access(";
      emitArguments(expr.arguments());
      output << ')';
      return;
    }
    if (resolved != nullptr &&
        resolved->intrinsic == IntrinsicKind::UniqueOwnerIsNull) {
      output << "::gti_internal::backend::unique_owner_is_null(";
      emitArguments(expr.arguments());
      output << ')';
      return;
    }
    if (resolved != nullptr && resolved->intrinsic == IntrinsicKind::Move) {
      output << "std::move(";
      emitArguments(expr.arguments());
      output << ')';
      return;
    }
    if (resolved != nullptr &&
        resolved->intrinsic == IntrinsicKind::AllocateStorage) {
      output << "::gti_internal::backend::allocate_storage<";
      if (!expr.typeArguments().empty()) {
        emitType(expr.typeArguments().front());
      }
      output << ">(";
      emitArguments(expr.arguments());
      output << ')';
      return;
    }
    if (resolved != nullptr && isStorageIntrinsic(resolved->intrinsic)) {
      output << "::gti_internal::backend::"
             << storageIntrinsicName(resolved->intrinsic) << '(';
      emitArguments(expr.arguments());
      output << ')';
      return;
    }
    if (isArraySizeCall(expr)) {
      const auto &member = static_cast<const Get &>(*expr.callee());
      output << "static_cast<std::uint64_t>((";
      emitExpression(member.object());
      output << ").size())";
      return;
    }
    if (isStringViewSizeCall(expr)) {
      const auto &member = static_cast<const Get &>(*expr.callee());
      output << "static_cast<std::uint64_t>((";
      emitExpression(member.object());
      output << ").size())";
      return;
    }
    if (resolved != nullptr && resolved->declaration != nullptr &&
        !resolved->declaration->runtimeBinding()) {
      emitResolvedCallee(expr.callee(), *resolved,
                         !expr.typeArguments().empty());
    } else if (!expr.typeArguments().empty()) {
      if (const auto *member = dynamic_cast<const Get *>(expr.callee().get())) {
        output << '(';
        emitExpression(member->object());
        output << ").template " << member->name().lexeme;
      } else {
        emitExpression(expr.callee());
      }
    } else {
      emitExpression(expr.callee());
    }
    if (!expr.typeArguments().empty()) {
      output << '<';
      for (std::size_t index = 0; index < expr.typeArguments().size();
           ++index) {
        if (index > 0) {
          output << ", ";
        }
        emitType(expr.typeArguments()[index]);
      }
      output << '>';
    }
    output << '(';
    const FunctionInfo *calledFunction =
        resolved == nullptr || resolved->declaration == nullptr
            ? nullptr
            : semantics.findFunction(*resolved->declaration);
    for (std::size_t index = 0; index < expr.arguments().size(); ++index) {
      if (index > 0) {
        output << ", ";
      }
      const bool countedTextBuffer =
          resolved != nullptr && resolved->declaration != nullptr &&
          resolved->declaration->hasCLinkage() &&
          ((calledFunction != nullptr &&
            index < calledFunction->parameterTypes.size() &&
            calledFunction->parameterTypes[index] ==
                SemanticType::StringView) ||
           (calledFunction == nullptr &&
            index < resolved->declaration->parameters().size() &&
            isGtiInternalTextView(
                resolved->declaration->parameters()[index].type)));
      if (countedTextBuffer) {
        output << "::gti_internal::backend::to_c_string_view(";
        emitExpression(expr.arguments().at(index));
        output << ')';
      } else {
        emitExpression(expr.arguments().at(index));
      }
    }
    output << ')';
  }

  void visitConditionalExpr(const ConditionalExpr &expr) override {
    output << "(static_cast<std::remove_cvref_t<decltype(";
    emitConditionalSelection(expr);
    output << ")>>(";
    emitConditionalSelection(expr);
    output << "))";
  }

  void visitConversionExpr(const Conversion &expr) override {
    output << "::gti_internal::backend::numeric_cast<";
    emitType(expr.targetType());
    output << ">(";
    emitExpression(expr.value());
    output << ')';
  }

  void visitDirectInitializerExpr(const DirectInitializer &expr) override {
    output << '{';
    emitArguments(expr.arguments());
    output << '}';
  }

  void visitDereferenceSetExpr(const DereferenceSet &expr) override {
    emitAssignmentExpression(
        expr.oper(),
        [&] {
          if (hasUnsafeOperation(expr, UnsafeOperationKind::RawDereference)) {
            output << "(*";
            emitExpression(expr.object());
            output << ')';
          } else if (semantics.findOperator(expr) != nullptr) {
            emitResolvedOperator(expr, expr.object());
          } else {
            output << "::gti_internal::backend::owner_access(";
            emitExpression(expr.object());
            output << ')';
          }
        },
        expr.value());
  }

  void visitGetExpr(const Get &expr) override {
    if (expr.access().kind == TokenKind::ARROW) {
      if (hasUnsafeOperation(expr, UnsafeOperationKind::RawMember)) {
        emitExpression(expr.object());
        output << "->" << expr.name().lexeme;
        return;
      }
      output << '(';
      if (semantics.findOperator(expr) != nullptr) {
        emitResolvedOperator(expr, expr.object());
      } else {
        output << "::gti_internal::backend::owner_access(";
        emitExpression(expr.object());
        output << ')';
      }
      output << ")." << expr.name().lexeme;
    } else {
      output << '(';
      emitExpression(expr.object());
      output << ")." << expr.name().lexeme;
    }
  }

  void visitGroupingExpr(const Grouping &expr) override {
    output << '(';
    emitExpression(expr.expression());
    output << ')';
  }

  void visitIndexExpr(const Index &expr) override {
    if (hasUnsafeOperation(expr, UnsafeOperationKind::RawIndex)) {
      output << '(';
      emitExpression(expr.object());
      output << '[';
      emitExpression(expr.index());
      output << "])";
    } else if (semantics.findOperator(expr) != nullptr) {
      emitResolvedOperator(expr, expr.object(), &expr.index());
    } else {
      output << (isStringViewIndex(expr)
                     ? "::gti_internal::backend::string_view_at("
                     : "::gti_internal::backend::array_at(");
      emitExpression(expr.object());
      output << ", ";
      emitExpression(expr.index());
      output << ')';
    }
  }

  void visitIndexSetExpr(const IndexSet &expr) override {
    const auto emitTarget = [&] {
      if (hasUnsafeOperation(expr, UnsafeOperationKind::RawIndex)) {
        output << '(';
        emitExpression(expr.object());
        output << '[';
        emitExpression(expr.index());
        output << "])";
      } else if (semantics.findOperator(expr) != nullptr) {
        emitResolvedOperator(expr, expr.object(), &expr.index());
      } else {
        output << "::gti_internal::backend::array_at(";
        emitExpression(expr.object());
        output << ", ";
        emitExpression(expr.index());
        output << ')';
      }
    };
    const SemanticType *targetType = semantics.findType(expr);
    if (expr.oper().kind != TokenKind::EQUAL && targetType != nullptr &&
        targetType->kind == SemanticType::RawPointer &&
        hasUnsafeOperation(expr, UnsafeOperationKind::PointerArithmetic)) {
      emitNativeAssignmentExpression(expr.oper(), emitTarget, expr.value());
    } else {
      emitAssignmentExpression(expr.oper(), emitTarget, expr.value());
    }
  }

  void visitLambdaExpr(const Lambda &expr) override {
    output << '[';
    for (std::size_t index = 0; index < expr.captures().size(); ++index) {
      if (index > 0) {
        output << ", ";
      }
      const LambdaCapture &capture = expr.captures()[index];
      output << capture.name.lexeme;
      if (capture.explicitInitializer()) {
        output << " = ";
        emitExpression(capture.initializer);
      }
    }
    output << "](";
    emitParameters(expr.parameters());
    output << ") -> ";
    emitType(expr.returnType());
    output << " {\n";

    const TypeRef *enclosingReturnType = currentReturnType;
    const SemanticType enclosingReturnSemanticType = currentReturnSemanticType;
    currentReturnType = &expr.returnType();
    const LambdaInfo *info = semantics.findLambda(expr);
    currentReturnSemanticType =
        info == nullptr ? SemanticType::Unknown : info->returnType;
    ++indentation;
    for (const StmtPtr &statement : expr.body()) {
      statement->accept(*this);
    }
    --indentation;
    currentReturnType = enclosingReturnType;
    currentReturnSemanticType = enclosingReturnSemanticType;
    writeIndent();
    output << '}';
  }

  void visitLayoutQueryExpr(const LayoutQuery &expr) override {
    const std::optional<ConstantValue> constant = semantics.findConstant(expr);
    if (constant) {
      emitConstant(*constant, semantics.findType(expr));
      return;
    }
    throw std::logic_error(
        "C++ emission requires a frontend-resolved layout constant");
  }

  [[nodiscard]] static bool isFixedWidthIntegerType(const SemanticType &type) {
    return type == SemanticType::Int8 || type == SemanticType::Int16 ||
           type == SemanticType::Int32 || type == SemanticType::Int64 ||
           type == SemanticType::UInt8 || type == SemanticType::UInt16 ||
           type == SemanticType::UInt32 || type == SemanticType::UInt64;
  }

  [[nodiscard]] static SemanticType
  defaultIntegerLiteralType(std::uint64_t value) {
    if (value <=
        static_cast<std::uint64_t>(std::numeric_limits<std::int32_t>::max())) {
      return SemanticType::Int32;
    }
    if (value <=
        static_cast<std::uint64_t>(std::numeric_limits<std::int64_t>::max())) {
      return SemanticType::Int64;
    }
    return SemanticType::UInt64;
  }

  [[nodiscard]] static std::optional<std::uint64_t>
  integerLiteralMagnitude(const Expr &expression) {
    if (const auto *literal = dynamic_cast<const LiteralExpr *>(&expression)) {
      if (const auto *magnitude =
              std::get_if<std::uint64_t>(&literal->value())) {
        return *magnitude;
      }
      return std::nullopt;
    }
    if (const auto *grouping = dynamic_cast<const Grouping *>(&expression)) {
      return integerLiteralMagnitude(*grouping->expression());
    }
    return std::nullopt;
  }

  void emitIntegerLiteral(std::uint64_t value) {
    output << value;
    if (value >
        static_cast<std::uint64_t>(std::numeric_limits<std::int64_t>::max())) {
      output << "ULL";
    }
  }

  void visitLiteralExpr(const LiteralExpr &expr) override {
    const Literal &literal = expr.value();
    if (std::holds_alternative<std::nullptr_t>(literal)) {
      output << "nullptr";
    } else if (const auto *value = std::get_if<std::uint64_t>(&literal)) {
      const SemanticType *type = semantics.findType(expr);
      const bool contextuallyTyped =
          type != nullptr &&
          (isFixedWidthIntegerType(*type) ||
           type->kind == SemanticType::TypeParameter) &&
          *type != defaultIntegerLiteralType(*value);
      if (contextuallyTyped) {
        output << "::gti_internal::backend::numeric_cast<";
        emitSemanticType(*type);
        output << ">(";
        emitIntegerLiteral(*value);
        output << ')';
      } else {
        emitIntegerLiteral(*value);
      }
    } else if (const auto *value = std::get_if<BinaryFloat>(&literal)) {
      emitFloat(*value);
    } else if (const auto *value = std::get_if<CharacterLiteral>(&literal)) {
      output << "std::uint8_t{" << static_cast<unsigned int>(value->value)
             << '}';
    } else if (const auto *value = std::get_if<std::string>(&literal)) {
      output << "std::string_view{" << quote(*value) << ", " << value->size()
             << '}';
    } else if (const auto *value = std::get_if<bool>(&literal)) {
      output << (*value ? "true" : "false");
    } else {
      output << "{}";
    }
  }

  void visitLogicalExpr(const Logical &expr) override {
    output << '(';
    emitContextualBool(expr.left());
    output << ' ' << operatorSpelling(expr.oper()) << ' ';
    emitContextualBool(expr.right());
    output << ')';
  }

  void visitPackExpansionExpr(const PackExpansion &expr) override {
    output << "::gti_internal::backend::forward_pack_argument("
           << expr.name().lexeme << ")...";
  }

  void visitPostfixExpr(const Postfix &expr) override {
    if (hasUnsafeOperation(expr, UnsafeOperationKind::PointerArithmetic)) {
      output << '(';
      emitExpression(expr.expression());
      output << operatorSpelling(expr.oper()) << ')';
      return;
    }
    output << "::gti_internal::backend::"
           << (expr.oper().kind == TokenKind::PLUS_PLUS ? "post_increment("
                                                        : "post_decrement(");
    emitExpression(expr.expression());
    output << ')';
  }

  void visitQualifiedNameExpr(const QualifiedName &expr) override {
    if (const ResolvedEnumeratorInfo *enumerator =
            semantics.findEnumerator(expr)) {
      const EnumTypeInfo *owner = semantics.findEnumType(enumerator->owner);
      if (owner != nullptr && owner->payload) {
        emitSemanticType(SemanticType::enumType(enumerator->owner));
        output << '{';
        emitSemanticType(SemanticType::enumType(enumerator->owner));
        output << "::__gti_variant_" << enumerator->variantIndex << "{}}";
        return;
      }
    }
    emitResolvedName(expr, expr.name());
  }

  void visitThisExpr(const This &) override { output << "(*this)"; }

  void visitSetExpr(const Set &expr) override {
    const auto emitTarget = [&] {
      if (expr.access().kind == TokenKind::ARROW) {
        if (hasUnsafeOperation(expr, UnsafeOperationKind::RawMember)) {
          emitExpression(expr.object());
          output << "->" << expr.name().lexeme;
          return;
        }
        output << '(';
        if (semantics.findOperator(expr) != nullptr) {
          emitResolvedOperator(expr, expr.object());
        } else {
          output << "::gti_internal::backend::owner_access(";
          emitExpression(expr.object());
          output << ')';
        }
        output << ").";
      } else {
        output << '(';
        emitExpression(expr.object());
        output << ").";
      }
      output << expr.name().lexeme;
    };
    const SemanticType *targetType = semantics.findType(expr);
    if (expr.oper().kind != TokenKind::EQUAL && targetType != nullptr &&
        targetType->kind == SemanticType::RawPointer &&
        (hasUnsafeOperation(expr, UnsafeOperationKind::PointerArithmetic) ||
         hasUnsafeOperation(expr, UnsafeOperationKind::RawMember))) {
      emitNativeAssignmentExpression(expr.oper(), emitTarget, expr.value());
    } else {
      emitAssignmentExpression(expr.oper(), emitTarget, expr.value());
    }
  }

  void visitUnaryExpr(const Unary &expr) override {
    if (expr.oper().kind == TokenKind::PLUS_PLUS &&
        semantics.findOperator(expr) != nullptr) {
      emitResolvedOperator(expr, expr.right());
      return;
    }
    if (expr.oper().kind == TokenKind::PLUS_PLUS ||
        expr.oper().kind == TokenKind::MINUS_MINUS) {
      if (hasUnsafeOperation(expr, UnsafeOperationKind::PointerArithmetic)) {
        output << '(' << operatorSpelling(expr.oper());
        emitExpression(expr.right());
        output << ')';
        return;
      }
      output << "::gti_internal::backend::"
             << (expr.oper().kind == TokenKind::PLUS_PLUS ? "pre_increment("
                                                          : "pre_decrement(");
      emitExpression(expr.right());
      output << ')';
      return;
    }
    if (expr.oper().kind == TokenKind::STAR) {
      if (hasUnsafeOperation(expr, UnsafeOperationKind::RawDereference)) {
        output << "(*";
        emitExpression(expr.right());
        output << ')';
      } else if (semantics.findOperator(expr) != nullptr) {
        emitResolvedOperator(expr, expr.right());
      } else {
        output << "::gti_internal::backend::owner_access(";
        emitExpression(expr.right());
        output << ')';
      }
      return;
    }
    if (expr.oper().kind == TokenKind::AMPERSAND &&
        hasUnsafeOperation(expr, UnsafeOperationKind::AddressOf)) {
      output << "(&";
      emitExpression(expr.right());
      output << ')';
      return;
    }
    if (expr.oper().kind == TokenKind::BANG) {
      output << "(!";
      emitContextualBool(expr.right());
      output << ')';
      return;
    }
    if ((expr.oper().kind == TokenKind::PLUS ||
         expr.oper().kind == TokenKind::MINUS) &&
        semantics.isContextualIntegerOperand(expr)) {
      const SemanticType *targetType = semantics.findType(expr);
      if (targetType == nullptr) {
        throw std::logic_error(
            "Contextual integer operand requires a resolved semantic type");
      }
      output << "::gti_internal::backend::numeric_cast<";
      emitSemanticType(*targetType);
      output << ">(";
      if (expr.oper().kind == TokenKind::MINUS) {
        if (const std::optional<std::uint64_t> magnitude =
                integerLiteralMagnitude(*expr.right());
            magnitude && *magnitude == (std::uint64_t{1} << 63U)) {
          output << "(-9223372036854775807LL - 1)";
          output << ')';
          return;
        }
        output << "::gti_internal::backend::negate(";
        emitExpression(expr.right());
        output << ')';
      } else {
        output << "(+";
        emitExpression(expr.right());
        output << ')';
      }
      output << ')';
      return;
    }
    if (expr.oper().kind == TokenKind::MINUS) {
      if (const auto *literal =
              dynamic_cast<const LiteralExpr *>(expr.right().get());
          literal != nullptr) {
        const auto *magnitude = std::get_if<std::uint64_t>(&literal->value());
        if (magnitude != nullptr && *magnitude == (std::uint64_t{1} << 63U)) {
          output << "(-9223372036854775807LL - 1)";
          return;
        }
      }
      output << "::gti_internal::backend::negate(";
      emitExpression(expr.right());
      output << ')';
      return;
    }
    output << '(' << operatorSpelling(expr.oper());
    emitExpression(expr.right());
    output << ')';
  }

  void visitUnexpectedExpr(const Unexpected &expr) override {
    output << (standard == CppStandard::Cpp23 ? "std::unexpected("
                                              : "::nonstd::make_unexpected(");
    emitExpression(expr.error());
    output << ')';
  }

  void visitVariableExpr(const Variable &expr) override {
    emitResolvedName(expr, NamePath(expr.name()));
  }

