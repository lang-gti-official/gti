  void collectClassFields(const StmtList &members,
                          std::vector<const VariableDecl *> &fields) const {
    for (const StmtPtr &member : members) {
      if (const auto *conditional =
              dynamic_cast<const ConditionalStmt *>(member.get())) {
        if (const StmtList *branch = conditional->activeBranch(target)) {
          collectClassFields(*branch, fields);
        }
      } else if (const auto *field =
                     dynamic_cast<const VariableDecl *>(member.get())) {
        if (!field->isStatic()) {
          fields.push_back(field);
        }
      }
    }
  }

  void collectStaticFields(const StmtList &members,
                           std::vector<const VariableDecl *> &fields) const {
    for (const StmtPtr &member : members) {
      if (const auto *conditional =
              dynamic_cast<const ConditionalStmt *>(member.get())) {
        if (const StmtList *branch = conditional->activeBranch(target)) {
          collectStaticFields(*branch, fields);
        }
      } else if (const auto *field =
                     dynamic_cast<const VariableDecl *>(member.get())) {
        if (field->isStatic() && !field->isConstexpr()) {
          fields.push_back(field);
        }
      }
    }
  }

  void emitDeclaredDestructorState(const ClassLifecycleInfo &lifecycle) {
    if (!lifecycle.declaredDestructor ||
        lifecycle.declaredDestructor->declaration == nullptr) {
      return;
    }

    if (indentation > 0) {
      --indentation;
    }
    writeIndent();
    output << "private:\n";
    ++indentation;
    writeIndent();
    output << "bool " << lifecycleActiveName(lifecycle) << " = true;\n";
    writeIndent();
    output << "void " << lifecycleCleanupName(lifecycle) << "() noexcept;\n";
    deferredMemberDefinitions.push_back(
        {.kind = DeferredMemberKind::LifecycleCleanup,
         .owner = lifecycle.declaration,
         .lifecycle = &lifecycle,
         .namespaceScope = sourceNamespaces});
  }

  [[nodiscard]] const ClassBaseTypeInfo *
  stateBearingBase(const ClassDecl &declaration) const {
    const ClassTypeInfo *type = semantics.findClassType(declaration);
    if (type == nullptr) {
      return nullptr;
    }
    const auto found = std::find_if(
        type->bases.begin(), type->bases.end(),
        [](const ClassBaseTypeInfo &base) { return !base.interface; });
    return found == type->bases.end() ? nullptr : &*found;
  }

  void emitMoveConstructor(const ClassDecl &declaration,
                           const ClassLifecycleInfo &lifecycle,
                           const std::vector<const VariableDecl *> &fields) {
    const std::string &name = declaration.name().lexeme;
    writeIndent();
    output << name << '(' << name << " &&other) noexcept : ";
    bool emittedInitializer = false;
    if (const ClassBaseTypeInfo *base = stateBearingBase(declaration)) {
      emitSemanticType(base->type);
      output << "(std::move(other))";
      emittedInitializer = true;
    }
    for (std::size_t index = 0; index < fields.size(); ++index) {
      if (emittedInitializer) {
        output << ", ";
      }
      output << fields[index]->name().lexeme << "(std::move(other."
             << fields[index]->name().lexeme << "))";
      emittedInitializer = true;
    }
    if (emittedInitializer) {
      output << ", ";
    }
    output << lifecycleActiveName(lifecycle) << "(true) {\n";
    ++indentation;
    writeIndent();
    output << "other." << lifecycleActiveName(lifecycle) << " = false;\n";
    --indentation;
    writeIndent();
    output << "}\n";
  }

  void emitMoveAssignment(const ClassDecl &declaration,
                          const ClassLifecycleInfo &lifecycle,
                          const std::vector<const VariableDecl *> &fields) {
    const std::string &name = declaration.name().lexeme;
    writeIndent();
    output << name << " &operator=(" << name << " &&other) noexcept {\n";
    ++indentation;
    writeIndent();
    output << "if (this != &other) {\n";
    ++indentation;
    writeIndent();
    output << lifecycleCleanupName(lifecycle) << "();\n";
    if (const ClassBaseTypeInfo *base = stateBearingBase(declaration)) {
      writeIndent();
      emitSemanticType(base->type);
      output << "::operator=(std::move(other));\n";
    }
    for (const VariableDecl *field : fields) {
      writeIndent();
      output << field->name().lexeme << " = std::move(other."
             << field->name().lexeme << ");\n";
    }
    writeIndent();
    output << lifecycleActiveName(lifecycle) << " = true;\n";
    writeIndent();
    output << "other." << lifecycleActiveName(lifecycle) << " = false;\n";
    --indentation;
    writeIndent();
    output << "}\n";
    writeIndent();
    output << "return *this;\n";
    --indentation;
    writeIndent();
    output << "}\n";
  }

  void emitClassMember(const StmtPtr &member) {
    if (const auto *conditional =
            dynamic_cast<const ConditionalStmt *>(member.get())) {
      if (const StmtList *branch = conditional->activeBranch(target)) {
        for (const StmtPtr &selected : *branch) {
          emitClassMember(selected);
        }
      }
      return;
    }

    const bool enclosingField = emittingField;
    emittingField = dynamic_cast<const VariableDecl *>(member.get()) != nullptr;
    member->accept(*this);
    emittingField = enclosingField;
  }

  void emitClassLifecycle(const ClassDecl &declaration) {
    const ClassLifecycleInfo *lifecycle =
        semantics.findClassLifecycle(declaration);
    if (lifecycle == nullptr) {
      return;
    }

    if (lifecycle->requiresActiveDropState) {
      emitDeclaredDestructorState(*lifecycle);
    }

    if (indentation > 0) {
      --indentation;
    }
    writeIndent();
    output << "public:\n";
    ++indentation;

    const auto emitStatus = [&](SpecialMemberStatus status) {
      output << (status == SpecialMemberStatus::Generated ? " = default;\n"
                                                          : " = delete;\n");
    };
    const std::string &name = declaration.name().lexeme;
    std::vector<const VariableDecl *> fields;
    if (lifecycle->requiresActiveDropState) {
      collectClassFields(declaration.members(), fields);
    }
    if (lifecycle->defaultConstructor != SpecialMemberStatus::Declared) {
      writeIndent();
      output << name << "()";
      emitStatus(lifecycle->defaultConstructor);
    }

    writeIndent();
    output << name << "(const " << name << " &)";
    emitStatus(lifecycle->copyConstructor);
    if (lifecycle->requiresActiveDropState &&
        lifecycle->moveConstructor == SpecialMemberStatus::Generated) {
      emitMoveConstructor(declaration, *lifecycle, fields);
    } else {
      writeIndent();
      output << name << '(' << name << " &&)";
      emitStatus(lifecycle->moveConstructor);
    }
    writeIndent();
    output << name << " &operator=(const " << name << " &)";
    emitStatus(lifecycle->copyAssignment);
    if (lifecycle->requiresActiveDropState &&
        lifecycle->moveAssignment == SpecialMemberStatus::Generated) {
      emitMoveAssignment(declaration, *lifecycle, fields);
    } else {
      writeIndent();
      output << name << " &operator=(" << name << " &&)";
      emitStatus(lifecycle->moveAssignment);
    }
    if (lifecycle->destructor != SpecialMemberStatus::Declared) {
      writeIndent();
      if (lifecycle->polymorphic) {
        output << "virtual ";
      }
      output << '~' << name << "() noexcept";
      emitStatus(lifecycle->destructor);
    }
  }

  void emitCAbiRecordAssertions(const ClassDecl &declaration,
                                const ClassTypeInfo *info) {
    if (info == nullptr || !info->cAbiRecord || !info->cAbiLayout) {
      return;
    }
    const CAbiRecordLayout &layout = *info->cAbiLayout;
    const std::string &name = declaration.name().lexeme;
    writeIndent();
    output << "static_assert(std::is_standard_layout_v<" << name
           << "> && std::is_trivially_copyable_v<" << name
           << ">, \"GTI [[c_abi]] records must remain passive C-compatible "
              "values\");\n";
    writeIndent();
    output << "static_assert(sizeof(" << name << ") == " << layout.sizeBytes
           << ", \"native compiler disagrees with GTI record size\");\n";
    writeIndent();
    output << "static_assert(alignof(" << name
           << ") == " << layout.abiAlignmentBytes
           << ", \"native compiler disagrees with GTI record alignment\");\n";
    for (const CAbiRecordFieldLayout &field : layout.fields) {
      if (field.declaration == nullptr) {
        continue;
      }
      writeIndent();
      output << "static_assert(__builtin_offsetof(" << name << ", "
             << field.declaration->name().lexeme << ") == " << field.offsetBytes
             << ", \"native compiler disagrees with GTI field offset\");\n";
    }
  }

  void emitUnionAssertions(const ClassDecl &declaration,
                           const ClassTypeInfo *info) {
    if (info == nullptr || info->kind != ClassKind::Union ||
        !info->unionLayout) {
      return;
    }
    const UnionLayout &layout = *info->unionLayout;
    const std::string &name = declaration.name().lexeme;
    writeIndent();
    output << "static_assert(std::is_union_v<" << name
           << "> && std::is_trivially_copyable_v<" << name
           << ">, \"GTI unions must remain passive native unions\");\n";
    writeIndent();
    output << "static_assert(sizeof(" << name << ") == " << layout.sizeBytes
           << ", \"native compiler disagrees with GTI union size\");\n";
    writeIndent();
    output << "static_assert(alignof(" << name
           << ") == " << layout.abiAlignmentBytes
           << ", \"native compiler disagrees with GTI union alignment\");\n";
  }

  void emitArguments(const ExprList &arguments) {
    for (std::size_t index = 0; index < arguments.size(); ++index) {
      if (index > 0) {
        output << ", ";
      }
      emitExpression(arguments[index]);
    }
  }

  [[nodiscard]] bool isArraySizeCall(const Call &call) const {
    if (!call.arguments().empty() || !call.typeArguments().empty()) {
      return false;
    }
    const auto *member = dynamic_cast<const Get *>(call.callee().get());
    if (member == nullptr || member->name().lexeme != "size") {
      return false;
    }
    const SemanticType *objectType = semantics.findType(*member->object());
    return objectType != nullptr && objectType->kind == SemanticType::Array;
  }

  [[nodiscard]] bool isStringViewSizeCall(const Call &call) const {
    if (!call.arguments().empty() || !call.typeArguments().empty()) {
      return false;
    }
    const auto *member = dynamic_cast<const Get *>(call.callee().get());
    if (member == nullptr || member->name().lexeme != "size") {
      return false;
    }
    const SemanticType *objectType = semantics.findType(*member->object());
    return objectType != nullptr &&
           objectType->kind == SemanticType::StringView;
  }

  [[nodiscard]] bool isStringViewIndex(const Index &index) const {
    const SemanticType *objectType = semantics.findType(*index.object());
    return objectType != nullptr &&
           objectType->kind == SemanticType::StringView;
  }

  void emitCheckedBinaryCall(std::string_view function, const Binary &expr) {
    output << "::gti_internal::backend::" << function << '(';
    emitExpression(expr.left());
    output << ", ";
    emitExpression(expr.right());
    output << ')';
  }

  template <typename EmitTarget>
  void emitNativeAssignmentExpression(const Token &operation,
                                      EmitTarget emitTarget,
                                      const ExprPtr &value) {
    output << '(';
    emitTarget();
    output << ' ' << operatorSpelling(operation) << ' ';
    emitExpression(value);
    output << ')';
  }

  template <typename EmitTarget>
  void emitAssignmentExpression(const Token &operation, EmitTarget emitTarget,
                                const ExprPtr &value) {
    if (operation.kind == TokenKind::EQUAL) {
      output << '(';
      emitTarget();
      output << " = ";
      emitExpression(value);
      output << ')';
      return;
    }

    output << "::gti_internal::backend::"
           << compoundAssignmentHelper(operation.kind) << '(';
    emitTarget();
    output << ", ";
    emitExpression(value);
    output << ')';
  }

  void emitBinaryExpression(const Binary &expr, bool parenthesize) {
    if (semantics.findOperator(expr) != nullptr) {
      emitResolvedOperator(expr, expr.left(), &expr.right());
      return;
    }
    switch (expr.oper().kind) {
    case TokenKind::PLUS:
      emitCheckedBinaryCall("add", expr);
      return;
    case TokenKind::MINUS:
      emitCheckedBinaryCall("subtract", expr);
      return;
    case TokenKind::STAR:
      emitCheckedBinaryCall("multiply", expr);
      return;
    case TokenKind::SLASH:
      emitCheckedBinaryCall("divide", expr);
      return;
    case TokenKind::PERCENT:
      emitCheckedBinaryCall("modulo", expr);
      return;
    case TokenKind::SHIFT_LEFT:
      emitCheckedBinaryCall("shift_left", expr);
      return;
    case TokenKind::SHIFT_RIGHT:
      emitCheckedBinaryCall("shift_right", expr);
      return;
    default:
      break;
    }
    if (parenthesize) {
      output << '(';
    }
    emitExpression(expr.left());
    output << ' ' << operatorSpelling(expr.oper()) << ' ';
    emitExpression(expr.right());
    if (parenthesize) {
      output << ')';
    }
  }

  void emitCAbiType(const SemanticType &type, const TypeRef &fallback) {
    if (type == SemanticType::StringView ||
        (type == SemanticType::Unknown && isGtiInternalTextView(fallback))) {
      output << "::gti_c_string_view";
      return;
    }
    if (type != SemanticType::Unknown) {
      emitSemanticType(type);
      return;
    }
    emitType(fallback);
  }

  void emitExternCSignature(const FunctionDecl &function) {
    const FunctionInfo *info = semantics.findFunction(function);
    emitCAbiType(info == nullptr ? SemanticType::Unknown : info->returnType,
                 function.returnType());
    const std::string_view symbol =
        info != nullptr && !info->externalSymbol.empty()
            ? std::string_view(info->externalSymbol)
            : std::string_view(function.name().lexeme);
    output << ' ' << symbol << '(';
    for (std::size_t index = 0; index < function.parameters().size(); ++index) {
      if (index != 0) {
        output << ", ";
      }
      const Parameter &parameter = function.parameters()[index];
      const SemanticType type =
          info == nullptr || index >= info->parameterTypes.size()
              ? SemanticType::Unknown
              : info->parameterTypes[index];
      emitCAbiType(type, parameter.type);
      if (!parameter.name.lexeme.empty()) {
        output << ' ' << parameter.name.lexeme;
      }
    }
    output << ")";
  }

  void emitExternCBlock(const ExternCDecl &declaration) {
    writeIndent();
    output << "extern \"C\" {\n";
    ++indentation;
    for (const StmtPtr &statement : declaration.declarations()) {
      const auto *function =
          dynamic_cast<const FunctionDecl *>(statement.get());
      if (function == nullptr) {
        continue;
      }
      writeIndent();
      emitExternCSignature(*function);
      output << ";\n";
    }
    --indentation;
    writeIndent();
    output << "}\n";
  }

  void emitForwardDeclarations(const Program &program) {
    const bool emittedTypes =
        emitTypeForwardDeclarations(program.declarations());
    const bool emittedAliases = emitAliasDeclarations(program.declarations());
    const bool emittedFunctions =
        emitFunctionForwardDeclarations(program.declarations());
    if (emittedTypes || emittedAliases || emittedFunctions) {
      output << '\n';
    }
  }

  bool emitTypeForwardDeclarations(const StmtList &declarations) {
    bool emitted = false;
    for (const StmtPtr &declaration : declarations) {
      if (const auto *conditional =
              dynamic_cast<const ConditionalStmt *>(declaration.get())) {
        if (const StmtList *branch = conditional->activeBranch(target)) {
          emitted = emitTypeForwardDeclarations(*branch) || emitted;
        }
      } else if (const auto *classDecl =
                     dynamic_cast<const ClassDecl *>(declaration.get())) {
        const ClassTypeInfo *classInfo = semantics.findClassType(*classDecl);
        if (classInfo != nullptr &&
            classInfo->compilerCapability != CompilerCapabilityTypeKind::None) {
          continue;
        }
        if (classInfo != nullptr && classInfo->cOpaqueHandle) {
          writeIndent();
          output << "using " << classDecl->name().lexeme << " = ::";
          for (std::size_t index = 0; index < classInfo->namespaceScope.size();
               ++index) {
            output << (index == 0 && classInfo->namespaceScope[index] == "std"
                           ? emittedStandardNamespace
                           : std::string_view(classInfo->namespaceScope[index]))
                   << "::";
          }
          output << classDecl->name().lexeme << ";\n";
          emitted = true;
          continue;
        }
        emitTemplateDeclaration(classDecl->genericParameters());
        writeIndent();
        output << (classDecl->kind() == ClassKind::Struct  ? "struct "
                   : classDecl->kind() == ClassKind::Union ? "union "
                                                           : "class ")
               << classDecl->name().lexeme << ";\n";
        emitted = true;
      } else if (const auto *enumDecl =
                     dynamic_cast<const EnumDecl *>(declaration.get())) {
        writeIndent();
        const EnumTypeInfo *info = semantics.findEnumType(*enumDecl);
        if (info != nullptr && info->payload) {
          output << "struct " << enumDecl->name().lexeme << ";\n";
        } else {
          output << "enum class " << enumDecl->name().lexeme << " : ";
          emitEnumUnderlyingType(*enumDecl);
          output << ";\n";
        }
        emitted = true;
      }
    }
    for (const StmtPtr &declaration : declarations) {
      if (const auto *namespaceDecl =
              dynamic_cast<const NamespaceDecl *>(declaration.get())) {
        writeIndent();
        output << "namespace " << emittedNamespaceName(namespaceDecl->name())
               << " {\n";
        sourceNamespaces.emplace_back(namespaceDecl->name().lexeme);
        ++indentation;
        emitTypeForwardDeclarations(namespaceDecl->declarations());
        --indentation;
        sourceNamespaces.pop_back();
        writeIndent();
        output << "}\n";
        emitted = true;
      }
    }
    return emitted;
  }

  bool emitAliasDeclarations(const StmtList &declarations) {
    bool emitted = false;
    for (const StmtPtr &declaration : declarations) {
      if (const auto *conditional =
              dynamic_cast<const ConditionalStmt *>(declaration.get())) {
        if (const StmtList *branch = conditional->activeBranch(target)) {
          emitted = emitAliasDeclarations(*branch) || emitted;
        }
      } else if (const auto *alias = dynamic_cast<const NamespaceAliasDecl *>(
                     declaration.get())) {
        writeIndent();
        output << "namespace " << alias->name().lexeme << " = ";
        emitNamePath(alias->target());
        output << ";\n";
        forwardedAliases.insert(alias);
        emitted = true;
      } else if (const auto *alias =
                     dynamic_cast<const TypeAliasDecl *>(declaration.get())) {
        emitTypeAliasDeclaration(*alias);
        forwardedTypeAliases.insert(alias);
        emitted = true;
      } else if (const auto *namespaceDecl =
                     dynamic_cast<const NamespaceDecl *>(declaration.get());
                 namespaceDecl != nullptr &&
                 containsAliasDeclaration(namespaceDecl->declarations())) {
        writeIndent();
        output << "namespace " << emittedNamespaceName(namespaceDecl->name())
               << " {\n";
        sourceNamespaces.emplace_back(namespaceDecl->name().lexeme);
        ++indentation;
        emitAliasDeclarations(namespaceDecl->declarations());
        --indentation;
        sourceNamespaces.pop_back();
        writeIndent();
        output << "}\n";
        emitted = true;
      }
    }
    return emitted;
  }

  bool emitFunctionForwardDeclarations(const StmtList &declarations) {
    bool emitted = false;
    for (const StmtPtr &declaration : declarations) {
      if (const auto *conditional =
              dynamic_cast<const ConditionalStmt *>(declaration.get())) {
        if (const StmtList *branch = conditional->activeBranch(target)) {
          emitted = emitFunctionForwardDeclarations(*branch) || emitted;
        }
      } else if (const auto *externC =
                     dynamic_cast<const ExternCDecl *>(declaration.get())) {
        emitExternCBlock(*externC);
        forwardedExternC.insert(externC);
        emitted = true;
      } else if (const auto *function =
                     dynamic_cast<const FunctionDecl *>(declaration.get());
                 function != nullptr && !function->runtimeBinding() &&
                 !isIntrinsicFunction(*function)) {
        emitTemplateDeclaration(function->genericParameters());
        writeIndent();
        emitFunctionSignature(*function);
        output << ";\n";
        emitted = true;
      }
    }
    for (const StmtPtr &declaration : declarations) {
      if (const auto *namespaceDecl =
              dynamic_cast<const NamespaceDecl *>(declaration.get());
          namespaceDecl != nullptr &&
          containsFunction(namespaceDecl->declarations())) {
        writeIndent();
        output << "namespace " << emittedNamespaceName(namespaceDecl->name())
               << " {\n";
        sourceNamespaces.emplace_back(namespaceDecl->name().lexeme);
        ++indentation;
        emitFunctionForwardDeclarations(namespaceDecl->declarations());
        --indentation;
        sourceNamespaces.pop_back();
        writeIndent();
        output << "}\n";
        emitted = true;
      }
    }
    return emitted;
  }

  bool emitGlobalVariableForwardDeclarations(const StmtList &declarations) {
    bool emitted = false;
    for (const StmtPtr &declaration : declarations) {
      if (const auto *conditional =
              dynamic_cast<const ConditionalStmt *>(declaration.get())) {
        if (const StmtList *branch = conditional->activeBranch(target)) {
          emitted = emitGlobalVariableForwardDeclarations(*branch) || emitted;
        }
        continue;
      }
      if (const auto *nameSpace =
              dynamic_cast<const NamespaceDecl *>(declaration.get())) {
        writeIndent();
        output << "namespace " << emittedNamespaceName(nameSpace->name())
               << " {\n";
        sourceNamespaces.emplace_back(nameSpace->name().lexeme);
        ++indentation;
        const bool nested =
            emitGlobalVariableForwardDeclarations(nameSpace->declarations());
        --indentation;
        sourceNamespaces.pop_back();
        writeIndent();
        output << "}\n";
        emitted = nested || emitted;
        continue;
      }
      const auto *variable =
          dynamic_cast<const VariableDecl *>(declaration.get());
      if (variable == nullptr) {
        continue;
      }
      const BindingInfo *binding = semantics.findBinding(*variable);
      if (variable->isStatic()) {
        namespaceStaticVariables.insert(variable);
        if (binding != nullptr) {
          namespaceStaticVariableSymbols.insert(binding->symbol);
        }
        // Class definitions may be dependency-scheduled ahead of a source-
        // earlier internal-linkage global whose initializer they reference.
        // A private generated holder gives that binding a complete declaration
        // without changing its one-translation-unit visibility or moving the
        // definition/initialization out of source order.
        writeIndent();
        output << "struct " << emittedStaticVariableHolderName(*variable)
               << " { static ";
        emitGlobalVariableType(*variable, binding, true);
        output << " value; };\n";
        emitted = true;
        continue;
      }
      writeIndent();
      output << "extern ";
      emitGlobalVariableType(*variable, binding, true);
      output << ' ' << emittedVariableName(*variable) << ";\n";
      emitted = true;
    }
    if (emitted) {
      output << '\n';
    }
    return emitted;
  }

  [[nodiscard]] bool containsAliasDeclaration(const StmtList &declarations) {
    for (const StmtPtr &declaration : declarations) {
      if (const auto *conditional =
              dynamic_cast<const ConditionalStmt *>(declaration.get())) {
        if (const StmtList *branch = conditional->activeBranch(target);
            branch != nullptr && containsAliasDeclaration(*branch)) {
          return true;
        }
        continue;
      }
      if (dynamic_cast<const NamespaceAliasDecl *>(declaration.get()) !=
              nullptr ||
          dynamic_cast<const TypeAliasDecl *>(declaration.get()) != nullptr) {
        return true;
      }
      if (const auto *namespaceDecl =
              dynamic_cast<const NamespaceDecl *>(declaration.get());
          namespaceDecl != nullptr &&
          containsAliasDeclaration(namespaceDecl->declarations())) {
        return true;
      }
    }
    return false;
  }

  [[nodiscard]] bool containsFunction(const StmtList &declarations) {
    for (const StmtPtr &declaration : declarations) {
      if (const auto *conditional =
              dynamic_cast<const ConditionalStmt *>(declaration.get())) {
        if (const StmtList *branch = conditional->activeBranch(target);
            branch != nullptr && containsFunction(*branch)) {
          return true;
        }
        continue;
      }
      if (const auto *externC =
              dynamic_cast<const ExternCDecl *>(declaration.get())) {
        if (containsFunction(externC->declarations())) {
          return true;
        }
        continue;
      }
      if (const auto *function =
              dynamic_cast<const FunctionDecl *>(declaration.get());
          function != nullptr && !function->runtimeBinding() &&
          !isIntrinsicFunction(*function)) {
        return true;
      }
      if (const auto *namespaceDecl =
              dynamic_cast<const NamespaceDecl *>(declaration.get());
          namespaceDecl != nullptr &&
          containsFunction(namespaceDecl->declarations())) {
        return true;
      }
    }
    return false;
  }

  [[nodiscard]] bool containsRuntimeBinding(const StmtList &declarations) {
    for (const StmtPtr &declaration : declarations) {
      if (const auto *conditional =
              dynamic_cast<const ConditionalStmt *>(declaration.get())) {
        if (const StmtList *branch = conditional->activeBranch(target);
            branch != nullptr && containsRuntimeBinding(*branch)) {
          return true;
        }
        continue;
      }
      if (const auto *function =
              dynamic_cast<const FunctionDecl *>(declaration.get());
          function != nullptr && function->runtimeBinding()) {
        return true;
      }
      if (const auto *namespaceDecl =
              dynamic_cast<const NamespaceDecl *>(declaration.get());
          namespaceDecl != nullptr &&
          containsRuntimeBinding(namespaceDecl->declarations())) {
        return true;
      }
    }
    return false;
  }

  [[nodiscard]] bool containsCAbiTextView(const StmtList &declarations) {
    for (const StmtPtr &declaration : declarations) {
      if (const auto *conditional =
              dynamic_cast<const ConditionalStmt *>(declaration.get())) {
        if (const StmtList *branch = conditional->activeBranch(target);
            branch != nullptr && containsCAbiTextView(*branch)) {
          return true;
        }
        continue;
      }
      if (const auto *namespaceDecl =
              dynamic_cast<const NamespaceDecl *>(declaration.get())) {
        if (containsCAbiTextView(namespaceDecl->declarations())) {
          return true;
        }
        continue;
      }
      if (const auto *externC =
              dynamic_cast<const ExternCDecl *>(declaration.get())) {
        if (containsCAbiTextView(externC->declarations())) {
          return true;
        }
        continue;
      }
      const auto *function =
          dynamic_cast<const FunctionDecl *>(declaration.get());
      if (function == nullptr || !function->hasCLinkage()) {
        continue;
      }
      if (const FunctionInfo *info = semantics.findFunction(*function)) {
        if (std::find(info->parameterTypes.begin(), info->parameterTypes.end(),
                      SemanticType::StringView) != info->parameterTypes.end()) {
          return true;
        }
      }
      if (std::any_of(function->parameters().begin(),
                      function->parameters().end(),
                      [this](const Parameter &parameter) {
                        return isGtiInternalTextView(parameter.type);
                      })) {
        return true;
      }
    }
    return false;
  }

  [[nodiscard]] static bool containsExpected(const TypeRef &type) {
    if (type.name.last().kind == TokenKind::EXPECTED) {
      return true;
    }
    for (const TypeRef &argument : type.arguments) {
      if (containsExpected(argument)) {
        return true;
      }
    }
    return false;
  }

  [[nodiscard]] bool containsExpectedExpression(const ExprPtr &expression) {
    if (!expression) {
      return false;
    }
    const Expr *raw = expression.get();
    if (const auto *assign = dynamic_cast<const Assign *>(raw)) {
      return containsExpectedExpression(assign->value());
    }
    if (const auto *initializer = dynamic_cast<const ArrayInitializer *>(raw)) {
      return std::any_of(initializer->elements().begin(),
                         initializer->elements().end(),
                         [this](const ExprPtr &element) {
                           return containsExpectedExpression(element);
                         });
    }
    if (const auto *binary = dynamic_cast<const Binary *>(raw)) {
      return containsExpectedExpression(binary->left()) ||
             containsExpectedExpression(binary->right());
    }
    if (const auto *call = dynamic_cast<const Call *>(raw)) {
      return containsExpectedExpression(call->callee()) ||
             std::any_of(call->typeArguments().begin(),
                         call->typeArguments().end(), containsExpected) ||
             std::any_of(call->arguments().begin(), call->arguments().end(),
                         [this](const ExprPtr &argument) {
                           return containsExpectedExpression(argument);
                         });
    }
    if (const auto *conditional = dynamic_cast<const ConditionalExpr *>(raw)) {
      return containsExpectedExpression(conditional->condition()) ||
             containsExpectedExpression(conditional->thenExpression()) ||
             containsExpectedExpression(conditional->elseExpression());
    }
    if (const auto *conversion = dynamic_cast<const Conversion *>(raw)) {
      return containsExpected(conversion->targetType()) ||
             containsExpectedExpression(conversion->value());
    }
    if (const auto *initializer =
            dynamic_cast<const DirectInitializer *>(raw)) {
      return std::any_of(initializer->arguments().begin(),
                         initializer->arguments().end(),
                         [this](const ExprPtr &argument) {
                           return containsExpectedExpression(argument);
                         });
    }
    if (const auto *set = dynamic_cast<const DereferenceSet *>(raw)) {
      return containsExpectedExpression(set->object()) ||
             containsExpectedExpression(set->value());
    }
    if (const auto *get = dynamic_cast<const Get *>(raw)) {
      return containsExpectedExpression(get->object());
    }
    if (const auto *grouping = dynamic_cast<const Grouping *>(raw)) {
      return containsExpectedExpression(grouping->expression());
    }
    if (const auto *index = dynamic_cast<const Index *>(raw)) {
      return containsExpectedExpression(index->object()) ||
             containsExpectedExpression(index->index());
    }
    if (const auto *set = dynamic_cast<const IndexSet *>(raw)) {
      return containsExpectedExpression(set->object()) ||
             containsExpectedExpression(set->index()) ||
             containsExpectedExpression(set->value());
    }
    if (const auto *lambda = dynamic_cast<const Lambda *>(raw)) {
      if (containsExpected(lambda->returnType()) ||
          std::any_of(lambda->parameters().begin(), lambda->parameters().end(),
                      [](const Parameter &parameter) {
                        return containsExpected(parameter.type);
                      })) {
        return true;
      }
      return containsExpectedType(lambda->body());
    }
    if (const auto *logical = dynamic_cast<const Logical *>(raw)) {
      return containsExpectedExpression(logical->left()) ||
             containsExpectedExpression(logical->right());
    }
    if (const auto *postfix = dynamic_cast<const Postfix *>(raw)) {
      return containsExpectedExpression(postfix->expression());
    }
    if (const auto *set = dynamic_cast<const Set *>(raw)) {
      return containsExpectedExpression(set->object()) ||
             containsExpectedExpression(set->value());
    }
    if (const auto *unary = dynamic_cast<const Unary *>(raw)) {
      return containsExpectedExpression(unary->right());
    }
    if (const auto *unexpected = dynamic_cast<const Unexpected *>(raw)) {
      return containsExpectedExpression(unexpected->error());
    }
    return false;
  }

  [[nodiscard]] bool containsExpectedType(const StmtList &statements) {
    for (const StmtPtr &statement : statements) {
      if (const auto *conditional =
              dynamic_cast<const ConditionalStmt *>(statement.get())) {
        if (const StmtList *branch = conditional->activeBranch(target);
            branch != nullptr && containsExpectedType(*branch)) {
          return true;
        }
      } else if (const auto *externC =
                     dynamic_cast<const ExternCDecl *>(statement.get())) {
        if (containsExpectedType(externC->declarations())) {
          return true;
        }
      } else if (const auto *function =
                     dynamic_cast<const FunctionDecl *>(statement.get())) {
        if (containsExpected(function->returnType())) {
          return true;
        }
        for (const Parameter &parameter : function->parameters()) {
          if (containsExpected(parameter.type)) {
            return true;
          }
        }
        if (function->body() &&
            containsExpectedType(function->body()->statements())) {
          return true;
        }
      } else if (const auto *constructor =
                     dynamic_cast<const ConstructorDecl *>(statement.get())) {
        for (const Parameter &parameter : constructor->parameters()) {
          if (containsExpected(parameter.type)) {
            return true;
          }
        }
        for (const ConstructorInitializer &initializer :
             constructor->initializers()) {
          for (const ExprPtr &argument : initializer.arguments) {
            if (containsExpectedExpression(argument)) {
              return true;
            }
          }
        }
        if (constructor->body() &&
            containsExpectedType(constructor->body()->statements())) {
          return true;
        }
      } else if (const auto *destructor =
                     dynamic_cast<const DestructorDecl *>(statement.get())) {
        if (containsExpectedType(destructor->body()->statements())) {
          return true;
        }
      } else if (const auto *variable =
                     dynamic_cast<const VariableDecl *>(statement.get())) {
        if (containsExpected(variable->type()) ||
            containsExpectedExpression(variable->initializer())) {
          return true;
        }
      } else if (const auto *binding =
                     dynamic_cast<const StructuredBindingDecl *>(
                         statement.get())) {
        if (containsExpectedExpression(binding->initializer())) {
          return true;
        }
      } else if (const auto *alias =
                     dynamic_cast<const TypeAliasDecl *>(statement.get())) {
        if (containsExpected(alias->target())) {
          return true;
        }
      } else if (const auto *expression =
                     dynamic_cast<const ExpressionStmt *>(statement.get())) {
        if (containsExpectedExpression(expression->expression())) {
          return true;
        }
      } else if (const auto *returnStatement =
                     dynamic_cast<const ReturnStmt *>(statement.get())) {
        if (containsExpectedExpression(returnStatement->value())) {
          return true;
        }
      } else if (const auto *switchStatement =
                     dynamic_cast<const SwitchStmt *>(statement.get())) {
        if (containsExpectedExpression(switchStatement->expression())) {
          return true;
        }
        for (const SwitchArm &arm : switchStatement->arms()) {
          for (const SwitchLabel &label : arm.labels) {
            if (containsExpectedExpression(label.value)) {
              return true;
            }
          }
          if (containsExpectedType(arm.statements)) {
            return true;
          }
        }
      } else if (const auto *block =
                     dynamic_cast<const BlockStmt *>(statement.get())) {
        if (containsExpectedType(block->statements())) {
          return true;
        }
      } else if (const auto *classDecl =
                     dynamic_cast<const ClassDecl *>(statement.get())) {
        if (containsExpectedType(classDecl->members())) {
          return true;
        }
      } else if (const auto *namespaceDecl =
                     dynamic_cast<const NamespaceDecl *>(statement.get())) {
        if (containsExpectedType(namespaceDecl->declarations())) {
          return true;
        }
      } else if (const auto *forStmt =
                     dynamic_cast<const ForStmt *>(statement.get())) {
        if (statementContainsExpected(forStmt->initializer()) ||
            containsExpectedExpression(forStmt->condition()) ||
            containsExpectedExpression(forStmt->increment()) ||
            statementContainsExpected(forStmt->body())) {
          return true;
        }
      } else if (const auto *ifStmt =
                     dynamic_cast<const IfStmt *>(statement.get())) {
        if (containsExpectedExpression(ifStmt->condition()) ||
            statementContainsExpected(ifStmt->thenBranch()) ||
            statementContainsExpected(ifStmt->elseBranch())) {
          return true;
        }
      } else if (const auto *doWhile =
                     dynamic_cast<const DoWhileStmt *>(statement.get())) {
        if (statementContainsExpected(doWhile->body()) ||
            containsExpectedExpression(doWhile->condition())) {
          return true;
        }
      } else if (const auto *whileStmt =
                     dynamic_cast<const WhileStmt *>(statement.get())) {
        if (containsExpectedExpression(whileStmt->condition()) ||
            statementContainsExpected(whileStmt->body())) {
          return true;
        }
      }
    }
    return false;
  }

  [[nodiscard]] bool statementContainsExpected(const StmtPtr &statement) {
    if (!statement) {
      return false;
    }
    const Stmt *raw = statement.get();
    if (const auto *conditional = dynamic_cast<const ConditionalStmt *>(raw)) {
      const StmtList *branch = conditional->activeBranch(target);
      return branch != nullptr && containsExpectedType(*branch);
    }
    if (const auto *variable = dynamic_cast<const VariableDecl *>(raw)) {
      return containsExpected(variable->type()) ||
             containsExpectedExpression(variable->initializer());
    }
    if (const auto *binding =
            dynamic_cast<const StructuredBindingDecl *>(raw)) {
      return containsExpectedExpression(binding->initializer());
    }
    if (const auto *expression = dynamic_cast<const ExpressionStmt *>(raw)) {
      return containsExpectedExpression(expression->expression());
    }
    if (const auto *returnStatement = dynamic_cast<const ReturnStmt *>(raw)) {
      return containsExpectedExpression(returnStatement->value());
    }
    if (const auto *switchStatement = dynamic_cast<const SwitchStmt *>(raw)) {
      if (containsExpectedExpression(switchStatement->expression())) {
        return true;
      }
      for (const SwitchArm &arm : switchStatement->arms()) {
        for (const SwitchLabel &label : arm.labels) {
          if (containsExpectedExpression(label.value)) {
            return true;
          }
        }
        if (containsExpectedType(arm.statements)) {
          return true;
        }
      }
      return false;
    }
    if (const auto *block = dynamic_cast<const BlockStmt *>(raw)) {
      return containsExpectedType(block->statements());
    }
    if (const auto *forStmt = dynamic_cast<const ForStmt *>(raw)) {
      return statementContainsExpected(forStmt->initializer()) ||
             containsExpectedExpression(forStmt->condition()) ||
             containsExpectedExpression(forStmt->increment()) ||
             statementContainsExpected(forStmt->body());
    }
    if (const auto *ifStmt = dynamic_cast<const IfStmt *>(raw)) {
      return containsExpectedExpression(ifStmt->condition()) ||
             statementContainsExpected(ifStmt->thenBranch()) ||
             statementContainsExpected(ifStmt->elseBranch());
    }
    if (const auto *doWhile = dynamic_cast<const DoWhileStmt *>(raw)) {
      return statementContainsExpected(doWhile->body()) ||
             containsExpectedExpression(doWhile->condition());
    }
    if (const auto *whileStmt = dynamic_cast<const WhileStmt *>(raw)) {
      return containsExpectedExpression(whileStmt->condition()) ||
             statementContainsExpected(whileStmt->body());
    }
    return false;
  }

  [[nodiscard]] std::string
  emittedFunctionName(const FunctionDecl &function) const {
    if (function.operatorName()) {
      switch (function.operatorName()->kind) {
      case OverloadedOperator::Equal:
      case OverloadedOperator::NotEqual:
      case OverloadedOperator::Less:
      case OverloadedOperator::LessEqual:
      case OverloadedOperator::Greater:
      case OverloadedOperator::GreaterEqual:
        return std::string(
            operatorSourceSpelling(function.operatorName()->kind));
      case OverloadedOperator::Dereference:
      case OverloadedOperator::PreIncrement:
      case OverloadedOperator::Arrow:
      case OverloadedOperator::Subscript:
      case OverloadedOperator::Call:
      case OverloadedOperator::ContextualBool:
        break;
      }
    }
    if (function.runtimeBinding()) {
      return function.name().lexeme;
    }
    const FunctionInfo *info = semantics.findFunction(function);
    if (function.hasCLinkage()) {
      return info != nullptr && !info->externalSymbol.empty()
                 ? info->externalSymbol
                 : function.name().lexeme;
    }
    if (info != nullptr && info->entryPoint &&
        info->returnType == SemanticType::Int32) {
      return "__gti_entry";
    }
    if (info == nullptr || info->id == 0) {
      return function.name().lexeme;
    }
    if (info->virtualMethod) {
      return function.name().lexeme;
    }
    return "__gti_fn_" + std::to_string(info->id) + "_" +
           function.name().lexeme;
  }

  [[nodiscard]] bool isIntrinsicFunction(const FunctionDecl &function) const {
    const FunctionInfo *info = semantics.findFunction(function);
    return info != nullptr && info->intrinsic != IntrinsicKind::None;
  }

  void emitResolvedCallee(const ExprPtr &callee,
                          const ResolvedCallInfo &resolved,
                          bool explicitTypeArguments) {
    const FunctionDecl &function = *resolved.declaration;
    const std::string name = emittedFunctionName(function);
    if (dynamic_cast<const Variable *>(callee.get()) != nullptr) {
      if (resolved.dispatch == CallDispatch::Virtual && classDepth > 0 &&
          resolved.dispatchOwner.kind == SemanticType::Class) {
        output << "(static_cast<";
        if (function.receiverMutability() == ReceiverMutability::ReadOnly) {
          output << "const ";
        }
        emitSemanticType(resolved.dispatchOwner);
        output << " &>(*this)).";
      }
      output << name;
      return;
    }
    if (const auto *qualified =
            dynamic_cast<const QualifiedName *>(callee.get())) {
      const NamePath &path = qualified->name();
      for (std::size_t index = 0; index + 1 < path.segments.size(); ++index) {
        if (index != 0) {
          output << "::";
        }
        if (index == 0 && path.segments[index].lexeme == "std") {
          output << emittedStandardNamespace;
        } else {
          output << path.segments[index].lexeme;
        }
      }
      if (path.segments.size() > 1) {
        output << "::";
      }
      output << name;
      return;
    }
    if (const auto *member = dynamic_cast<const Get *>(callee.get())) {
      const bool qualify = resolved.dispatch == CallDispatch::Virtual &&
                           resolved.dispatchOwner.kind == SemanticType::Class;
      if (member->access().kind == TokenKind::ARROW &&
          hasUnsafeOperation(*member, UnsafeOperationKind::RawMember)) {
        if (qualify) {
          output << "(static_cast<";
          if (function.receiverMutability() == ReceiverMutability::ReadOnly) {
            output << "const ";
          }
          emitSemanticType(resolved.dispatchOwner);
          output << " &>(*(";
          emitExpression(member->object());
          output << "))).";
        } else {
          emitExpression(member->object());
          output << "->";
        }
        if (explicitTypeArguments) {
          output << "template ";
        }
        output << name;
        return;
      }
      output << '(';
      if (qualify) {
        output << "static_cast<";
        if (function.receiverMutability() == ReceiverMutability::ReadOnly) {
          output << "const ";
        }
        emitSemanticType(resolved.dispatchOwner);
        output << " &>(";
      }
      if (member->access().kind == TokenKind::ARROW) {
        if (semantics.findOperator(*member) != nullptr) {
          emitResolvedOperator(*member, member->object());
        } else {
          output << "::gti_internal::backend::owner_access(";
          emitExpression(member->object());
          output << ')';
        }
      } else {
        emitExpression(member->object());
      }
      if (qualify) {
        output << ')';
      }
      output << ").";
      if (explicitTypeArguments) {
        output << "template ";
      }
      output << name;
      return;
    }
    emitExpression(callee);
  }

  [[nodiscard]] bool currentClassHasConsumingCallOperator() const {
    if (currentClass == nullptr) {
      return false;
    }
    const auto contains = [&](const auto &self,
                              const StmtList &members) -> bool {
      for (const StmtPtr &member : members) {
        if (const auto *function =
                dynamic_cast<const FunctionDecl *>(member.get());
            function != nullptr && function->operatorName() &&
            function->operatorName()->kind == OverloadedOperator::Call &&
            function->receiverMutability() == ReceiverMutability::Consuming) {
          return true;
        }
        if (const auto *conditional =
                dynamic_cast<const ConditionalStmt *>(member.get())) {
          if (const StmtList *selected = conditional->activeBranch(target);
              selected != nullptr && self(self, *selected)) {
            return true;
          }
        }
      }
      return false;
    };
    return contains(contains, currentClass->members());
  }

  void emitFunctionSignature(const FunctionDecl &function) {
    const FunctionInfo *info = semantics.findFunction(function);
    const bool isMain =
        (info != nullptr ? info->entryPoint
                         : sourceNamespaces.empty() && classDepth == 0 &&
                               function.name().lexeme == "main") &&
        (info != nullptr ? info->returnType == SemanticType::Int32
                         : isInt32(function.returnType()));
    if (function.isStatic() && !emittingDeferredMember) {
      output << "static ";
    }
    const bool interfaceContract =
        currentClass != nullptr && currentClass->kind() == ClassKind::Interface;
    if (classDepth > 0 && !emittingDeferredMember &&
        ((info != nullptr && info->virtualMethod && !info->overrideMethod) ||
         interfaceContract) &&
        !function.isStatic()) {
      output << "virtual ";
    }
    if (isMain) {
      output << "int";
    } else {
      if (function.returnType().reference &&
          function.returnMutability() == Mutability::Immutable) {
        output << "const ";
      }
      emitType(function.returnType());
    }
    output << (function.returnType().reference ? " &" : " ");
    if (emittingDeferredMember && currentClass != nullptr) {
      emitCurrentClassSpecialization();
      output << "::";
    }
    output << emittedFunctionName(function) << '(';
    emitParameters(function.parameters());
    output << ')';
    const bool refQualifiedCallFamily =
        function.operatorName() &&
        function.operatorName()->kind == OverloadedOperator::Call &&
        currentClassHasConsumingCallOperator();
    if (classDepth > 0 && !function.isStatic() &&
        function.receiverMutability() == ReceiverMutability::ReadOnly) {
      output << " const";
      if (refQualifiedCallFamily) {
        output << " &";
      }
    } else if (classDepth > 0 && !function.isStatic() &&
               function.receiverMutability() == ReceiverMutability::Mutable &&
               refQualifiedCallFamily) {
      output << " &";
    } else if (classDepth > 0 && !function.isStatic() &&
               function.receiverMutability() == ReceiverMutability::Consuming) {
      output << " &&";
    }
    if (classDepth > 0 && !emittingDeferredMember && info != nullptr &&
        info->overrideMethod) {
      output << " override";
    }
  }

  void emitCurrentClassSpecialization() {
    if (currentClass == nullptr) {
      return;
    }
    output << currentClass->name().lexeme;
    if (currentClass->genericParameters().empty()) {
      return;
    }
    output << '<';
    for (std::size_t index = 0;
         index < currentClass->genericParameters().size(); ++index) {
      if (index != 0) {
        output << ", ";
      }
      const GenericParameter &parameter =
          currentClass->genericParameters()[index];
      output << parameter.name.lexeme;
      if (parameter.pack) {
        output << "...";
      }
    }
    output << '>';
  }

  void
  emitTemplateDeclaration(const std::vector<GenericParameter> &parameters) {
    if (parameters.empty()) {
      return;
    }
    writeIndent();
    output << "template <";
    for (std::size_t index = 0; index < parameters.size(); ++index) {
      if (index > 0) {
        output << ", ";
      }
      if (parameters[index].valueType) {
        // GTI value generics are uint64_t. The supported native targets use
        // a 64-bit size_t, and spelling an extent parameter as size_t keeps
        // std::array deduction exact across C++ implementations where
        // uint64_t and size_t are distinct underlying types.
        output << "std::size_t " << parameters[index].name.lexeme;
      } else {
        output << "typename" << (parameters[index].pack ? "... " : " ")
               << parameters[index].name.lexeme;
      }
    }
    output << ">\n";
  }

  [[nodiscard]] static bool
  isStructuralOperatorBridge(const FunctionDecl &function,
                             const FunctionInfo *info) {
    if (!function.operatorName() || info == nullptr || info->compilerPrivate ||
        !info->requirements.empty() || function.requiresClause()) {
      return false;
    }
    switch (function.operatorName()->kind) {
    case OverloadedOperator::Dereference:
      return function.parameters().empty() &&
             function.receiverMutability() == ReceiverMutability::ReadOnly &&
             info->returnType.kind == SemanticType::Reference &&
             info->returnType.arguments.size() == 1;
    case OverloadedOperator::PreIncrement:
      return function.parameters().empty() &&
             function.receiverMutability() == ReceiverMutability::Mutable &&
             info->returnType == SemanticType::Void;
    case OverloadedOperator::NotEqual:
      return function.receiverMutability() == ReceiverMutability::ReadOnly &&
             info->returnType == SemanticType::Bool &&
             info->parameterTypes.size() == 1 &&
             info->parameterTypes.front().kind == SemanticType::Reference &&
             info->parameterTypes.front().arguments.size() == 1 &&
             info->parameterTypes.front().referenceAccess ==
                 AccessMode::ReadOnly;
    default:
      return false;
    }
  }

  void emitStructuralOperatorAdapter(const FunctionDecl &function) {
    const FunctionInfo *info = semantics.findFunction(function);
    if (currentClass == nullptr ||
        currentClassAccess != AccessModifier::Public ||
        !isStructuralOperatorBridge(function, info)) {
      return;
    }

    writeIndent();
    output << "friend ";
    if (function.returnType().reference &&
        function.returnMutability() == Mutability::Immutable) {
      output << "const ";
    }
    emitType(function.returnType());
    output << (function.returnType().reference ? " &" : " ")
           << operatorFunctionName(function.operatorName()->kind) << '(';
    if (function.receiverMutability() == ReceiverMutability::ReadOnly) {
      output << "const ";
    }
    output << currentClass->name().lexeme << " &__gti_receiver";
    if (function.operatorName()->kind == OverloadedOperator::NotEqual) {
      output << ", ::gti_internal::backend::exact_type<";
      emitType(function.parameters().front().type);
      output << ">";
    }
    for (std::size_t index = 0; index < function.parameters().size(); ++index) {
      output << ", ";
      emitParameter(function.parameters()[index],
                    "__gti_argument_" + std::to_string(index));
    }
    output << ") { ";
    const bool returnsVoid =
        info != nullptr
            ? info->returnType == SemanticType::Void
            : function.returnType().name.last().kind == TokenKind::VOID;
    if (!returnsVoid) {
      output << "return ";
    }
    output << "__gti_receiver." << emittedFunctionName(function) << '(';
    for (std::size_t index = 0; index < function.parameters().size(); ++index) {
      if (index != 0) {
        output << ", ";
      }
      if (!function.parameters()[index].type.reference) {
        output << "std::move(";
      }
      output << "__gti_argument_" << index;
      if (!function.parameters()[index].type.reference) {
        output << ')';
      }
    }
    output << "); }\n";
  }

  void emitCallableAdapter(const FunctionDecl &function) {
    if (classDepth == 0 || !function.operatorName() ||
        function.operatorName()->kind != OverloadedOperator::Call ||
        !function.body() || currentClassLifecycle == nullptr ||
        currentClassLifecycle->declaration == nullptr) {
      return;
    }
    const FunctionInfo *info = semantics.findFunction(function);
    if (function.requiresClause() ||
        (info != nullptr &&
         (info->compilerPrivate || !info->requirements.empty()))) {
      return;
    }
    writeIndent();
    output << "friend ";
    if (function.returnType().reference &&
        function.returnMutability() == Mutability::Immutable) {
      output << "const ";
    }
    emitType(function.returnType());
    output << (function.returnType().reference ? " &" : " ") << "__gti_invoke(";
    if (function.receiverMutability() == ReceiverMutability::ReadOnly) {
      output << "const ";
    }
    output << currentClassLifecycle->declaration->name().lexeme
           << (function.receiverMutability() == ReceiverMutability::Consuming
                   ? " &&__gti_callable"
                   : " &__gti_callable");
    output << ", ";
    if (info != nullptr) {
      emitExactCallTagType(
          callableInvocationCapability(function.receiverMutability()),
          info->parameterTypes, {}, true);
    } else {
      output << "::gti_internal::backend::exact_call<"
                "::gti_internal::backend::callable_capability::";
      switch (function.receiverMutability()) {
      case ReceiverMutability::ReadOnly:
        output << "read_call";
        break;
      case ReceiverMutability::Mutable:
        output << "mutable_call";
        break;
      case ReceiverMutability::Consuming:
        output << "once_call";
        break;
      }
      for (const Parameter &parameter : function.parameters()) {
        output << ", ";
        output << "::gti_internal::backend::call_parameter<"
                  "::gti_internal::backend::callable_binding::";
        if (!parameter.type.reference) {
          output << "value";
        } else if (parameter.mutability == Mutability::Mutable) {
          output << "mutable_reference";
        } else {
          output << "read_reference";
        }
        output << ", ";
        emitType(parameter.type);
        output << '>';
      }
      output << '>';
    }
    for (std::size_t index = 0; index < function.parameters().size(); ++index) {
      output << ", ";
      emitParameter(function.parameters()[index],
                    "__gti_arg_" + std::to_string(index));
    }
    output << ") { ";
    const bool returnsVoid =
        info != nullptr
            ? info->returnType == SemanticType::Void
            : function.returnType().name.last().kind == TokenKind::VOID;
    if (!returnsVoid) {
      output << "return ";
    }
    if (function.receiverMutability() == ReceiverMutability::Consuming) {
      output << "std::move(__gti_callable).";
    } else {
      output << "__gti_callable.";
    }
    output << emittedFunctionName(function) << '(';
    for (std::size_t index = 0; index < function.parameters().size(); ++index) {
      if (index != 0) {
        output << ", ";
      }
      if (!function.parameters()[index].type.reference) {
        output << "std::move(";
      }
      output << "__gti_arg_" << index;
      if (!function.parameters()[index].type.reference) {
        output << ')';
      }
    }
    output << "); }\n";
  }

  void emitParameter(const Parameter &parameter, std::string_view name) {
    const BindingInfo *binding = semantics.findBinding(parameter);
    const bool rawPointer = binding != nullptr
                                ? binding->type.kind == SemanticType::RawPointer
                                : parameter.type.pointer.has_value();
    const bool moveOnlyOwner = binding != nullptr
                                   ? isMoveOnlyOwner(binding->traits) ||
                                         containsTypeParameter(binding->type)
                                   : isGtiInternalUniqueOwner(parameter.type) ||
                                         isGtiInternalStorage(parameter.type);
    const bool readOnlyReference =
        parameter.type.reference.has_value() &&
        parameter.mutability == Mutability::Immutable;
    if (readOnlyReference ||
        (parameter.mutability == Mutability::Immutable && !parameter.pack &&
         !moveOnlyOwner && !rawPointer &&
         (binding == nullptr || !binding->explicitlyMoved))) {
      output << "const ";
    }
    emitType(parameter.type);
    if (parameter.pack) {
      output << "...";
    }
    const bool byReference = parameter.type.reference.has_value();
    if (byReference) {
      output << " &";
    }
    if (!name.empty()) {
      output << (byReference ? "" : " ") << name;
    }
  }

  void emitParameters(const std::vector<Parameter> &parameters) {
    for (std::size_t index = 0; index < parameters.size(); ++index) {
      if (index > 0) {
        output << ", ";
      }
      const Parameter &parameter = parameters.at(index);
      emitParameter(parameter, parameter.name.lexeme);
    }
  }

  void emitProgramEntryAdapter() {
    if (ownedArgumentsEntry == nullptr) {
      return;
    }
    const FunctionInfo *entry = semantics.findFunction(*ownedArgumentsEntry);
    if (entry == nullptr || entry->entryKind == ProgramEntryKind::None) {
      return;
    }
    if (entry->entryKind == ProgramEntryKind::NoArguments) {
      output << "\nint main() { return ::__gti_program::"
             << emittedFunctionName(*ownedArgumentsEntry) << "(); }\n";
      return;
    }
    if (entry->parameterTypes.size() != 2 ||
        entry->parameterTypes[1].kind != SemanticType::Class ||
        entry->parameterTypes[1].arguments.size() != 1) {
      return;
    }
    const FunctionInfo *append =
        semantics.findFunction(entry->entryArgumentAppendFunction);
    if (append == nullptr || append->declaration == nullptr) {
      return;
    }

    output << "\nint main(int __gti_native_argc, "
              "char **__gti_native_argv) {\n";
    ++indentation;
    writeIndent();
    output << "if (__gti_native_argc < 0) {\n";
    ++indentation;
    writeIndent();
    output << "::gti_internal::backend::integer_domain_error("
              "\"negative program argument count\");\n";
    --indentation;
    writeIndent();
    output << "}\n";
    writeIndent();
    emitSemanticType(entry->parameterTypes[1]);
    output << " __gti_arguments{};\n";
    writeIndent();
    output << "for (int __gti_index = 0; __gti_index < "
              "__gti_native_argc; ++__gti_index) {\n";
    ++indentation;
    writeIndent();
    output << "__gti_arguments." << emittedFunctionName(*append->declaration)
           << '(';
    emitSemanticType(entry->parameterTypes[1].arguments.front());
    output << "(std::string_view(__gti_native_argv[__gti_index])));\n";
    --indentation;
    writeIndent();
    output << "}\n";
    writeIndent();
    output << "return ::__gti_program::"
           << emittedFunctionName(*ownedArgumentsEntry)
           << "(::gti_internal::backend::numeric_cast<std::int32_t>("
              "__gti_native_argc), std::move(__gti_arguments));\n";
    --indentation;
    output << "}\n";
  }

  void emitType(const TypeRef &type) { emitArrayType(type, 0); }

  void emitEnumUnderlyingType(const EnumDecl &declaration) {
    const EnumTypeInfo *info = semantics.findEnumType(declaration);
    if (info != nullptr) {
      emitSemanticType(info->underlyingType);
      return;
    }
    if (declaration.underlyingType()) {
      emitType(*declaration.underlyingType());
      return;
    }
    output << "std::int32_t";
  }

  void emitPayloadEnum(const EnumDecl &declaration, const EnumTypeInfo &info) {
    writeIndent();
    output << "struct " << declaration.name().lexeme << " {\n";
    ++indentation;
    for (const EnumeratorInfo &enumerator : info.enumerators) {
      writeIndent();
      output << "struct __gti_variant_" << enumerator.variantIndex << " {\n";
      ++indentation;
      for (std::size_t index = 0; index < enumerator.payloadTypes.size();
           ++index) {
        writeIndent();
        emitSemanticType(enumerator.payloadTypes[index]);
        output << " __gti_field_" << index << ";\n";
      }
      writeIndent();
      output << "friend bool operator==(const __gti_variant_"
             << enumerator.variantIndex << " &, const __gti_variant_"
             << enumerator.variantIndex << " &) = default;\n";
      --indentation;
      writeIndent();
      output << "};\n";
    }
    writeIndent();
    output << "std::variant<";
    for (std::size_t index = 0; index < info.enumerators.size(); ++index) {
      if (index != 0) {
        output << ", ";
      }
      output << "__gti_variant_" << info.enumerators[index].variantIndex;
    }
    output << "> __gti_value;\n";
    writeIndent();
    output << "friend bool operator==(const " << declaration.name().lexeme
           << " &, const " << declaration.name().lexeme << " &) = default;\n";
    --indentation;
    writeIndent();
    output << "};\n";
  }

  void emitTypeAliasDeclaration(const TypeAliasDecl &alias) {
    writeIndent();
    output << "using " << alias.name().lexeme << " = ";
    const TypeAliasInfo *info = semantics.findTypeAlias(alias);
    if (info != nullptr && info->type != SemanticType::Unknown) {
      emitSemanticType(info->type);
    } else {
      emitType(alias.target());
    }
    output << ";\n";
  }

  void emitSemanticType(const SemanticType &type) {
    switch (type.kind) {
    case SemanticType::Void:
      output << "void";
      return;
    case SemanticType::Int8:
      output << "std::int8_t";
      return;
    case SemanticType::Int16:
      output << "std::int16_t";
      return;
    case SemanticType::Int32:
      output << "std::int32_t";
      return;
    case SemanticType::Int64:
      output << "std::int64_t";
      return;
    case SemanticType::UInt8:
      output << "std::uint8_t";
      return;
    case SemanticType::UInt16:
      output << "std::uint16_t";
      return;
    case SemanticType::UInt32:
      output << "std::uint32_t";
      return;
    case SemanticType::UInt64:
      output << "std::uint64_t";
      return;
    case SemanticType::Float:
      output << "float";
      return;
    case SemanticType::Double:
      output << "double";
      return;
    case SemanticType::Bool:
      output << "bool";
      return;
    case SemanticType::Char:
      output << "std::uint8_t";
      return;
    case SemanticType::StringView:
      output << "std::string_view";
      return;
    case SemanticType::NullPtr:
      output << "std::nullptr_t";
      return;
    case SemanticType::RawPointer:
      if (type.pointerAccess == AccessMode::ReadOnly) {
        output << "const ";
      }
      if (!type.arguments.empty()) {
        emitSemanticType(type.arguments.front());
      } else {
        output << "void";
      }
      output << '*';
      return;
    case SemanticType::Array:
      output << "std::array<";
      if (!type.arguments.empty()) {
        emitSemanticType(type.arguments.front());
      } else {
        output << "void";
      }
      output << ", ";
      if (type.arrayLengthParameterId != 0) {
        const GenericParameterInfo *parameter =
            semantics.findGenericParameter(type.arrayLengthParameterId);
        output << (parameter == nullptr ? "0" : parameter->name.lexeme);
      } else {
        output << type.arrayLength;
      }
      output << '>';
      return;
    case SemanticType::Class: {
      const ClassTypeInfo *classInfo = semantics.findClassType(type.classId);
      if (classInfo == nullptr || classInfo->declaration == nullptr) {
        output << "void";
        return;
      }
      output << (classInfo->cOpaqueHandle ? "::" : "::__gti_program::");
      for (const std::string &scope : classInfo->namespaceScope) {
        output << (scope == "std" ? emittedStandardNamespace
                                  : std::string_view(scope))
               << "::";
      }
      output << classInfo->declaration->name().lexeme;
      if (!type.arguments.empty() || !type.valueArguments.empty()) {
        output << '<';
        bool separator = false;
        for (const SemanticType &argument : type.arguments) {
          if (separator) {
            output << ", ";
          }
          emitSemanticType(argument);
          separator = true;
        }
        for (const CompileTimeValue &argument : type.valueArguments) {
          if (separator) {
            output << ", ";
          }
          if (argument.kind == CompileTimeValue::UInt64) {
            output << argument.value;
          } else if (argument.kind == CompileTimeValue::Parameter) {
            const GenericParameterInfo *parameter =
                semantics.findGenericParameter(argument.parameterId);
            output << (parameter == nullptr ? "0" : parameter->name.lexeme);
          } else {
            output << '0';
          }
          separator = true;
        }
        output << '>';
      }
      return;
    }
    case SemanticType::Enum: {
      const EnumTypeInfo *enumInfo = semantics.findEnumType(type.enumId);
      if (enumInfo == nullptr || enumInfo->declaration == nullptr) {
        output << "void";
        return;
      }
      output << "::__gti_program::";
      for (const std::string &scope : enumInfo->namespaceScope) {
        output << (scope == "std" ? emittedStandardNamespace
                                  : std::string_view(scope))
               << "::";
      }
      output << enumInfo->declaration->name().lexeme;
      return;
    }
    case SemanticType::Reference:
      if (type.referenceAccess == AccessMode::ReadOnly) {
        output << "const ";
      }
      if (!type.arguments.empty()) {
        emitSemanticType(type.arguments.front());
      } else {
        output << "void";
      }
      output << " &";
      return;
    case SemanticType::UniqueOwner:
      output << "std::unique_ptr<";
      if (!type.arguments.empty()) {
        emitSemanticType(type.arguments.front());
      }
      output << '>';
      return;
    case SemanticType::Storage:
      output << "::gti_internal::backend::storage<";
      if (!type.arguments.empty()) {
        emitSemanticType(type.arguments.front());
      }
      output << '>';
      return;
    case SemanticType::TypeParameter:
    case SemanticType::TypePack: {
      const GenericParameterInfo *parameter =
          semantics.findGenericParameter(type.genericParameterId);
      output << (parameter == nullptr ? "void" : parameter->name.lexeme);
      if (type.kind == SemanticType::TypePack && type.concretePack) {
        output << "...";
      }
      return;
    }
    case SemanticType::Expected:
      output << (standard == CppStandard::Cpp23 ? "std::expected<"
                                                : "::nonstd::expected<");
      if (type.arguments.size() == 2) {
        emitSemanticType(type.arguments[0]);
        output << ", ";
        emitSemanticType(type.arguments[1]);
      }
      output << '>';
      return;
    default:
      output << "void";
      return;
    }
  }

  void emitArrayType(const TypeRef &type, std::size_t extentIndex) {
    if (extentIndex < type.arrayExtents.size()) {
      output << "std::array<";
      emitArrayType(type, extentIndex + 1);
      output << ", ";
      const ArrayExtentExprPtr &extent = type.arrayExtents[extentIndex];
      const CompileTimeValue *resolved =
          !extent ? nullptr : semantics.findArrayExtent(*extent);
      if (resolved != nullptr && resolved->kind == CompileTimeValue::UInt64) {
        output << resolved->value;
      } else if (extent && extent->isAtom()) {
        if (const auto *literal =
                std::get_if<std::uint64_t>(&extent->token.literal)) {
          output << *literal;
        } else {
          output << extent->token.lexeme;
        }
      } else if (extent) {
        output << arrayExtentSpelling(*extent);
      } else {
        output << '0';
      }
      output << '>';
      return;
    }
    emitBaseType(type);
  }

  void emitBaseType(const TypeRef &type) {
    if (type.pointeeConst.has_value()) {
      output << "const ";
    }
    emitUnqualifiedBaseType(type);
    if (type.pointer.has_value()) {
      output << '*';
    }
  }

  void emitUnqualifiedBaseType(const TypeRef &type) {
    if (isGtiInternalTextView(type)) {
      output << "std::string_view";
      return;
    }
    if (isGtiInternalUniqueOwner(type)) {
      output << "std::unique_ptr<";
      if (!type.arguments.empty()) {
        emitType(type.arguments.front());
      }
      output << '>';
      return;
    }
    if (isGtiInternalStorage(type)) {
      output << "::gti_internal::backend::storage<";
      if (!type.arguments.empty()) {
        emitType(type.arguments.front());
      }
      output << '>';
      return;
    }
    switch (type.name.last().kind) {
    case TokenKind::AUTO:
      output << "auto";
      return;
    case TokenKind::INT:
    case TokenKind::INT32:
      output << "std::int32_t";
      return;
    case TokenKind::INT8:
      output << "std::int8_t";
      return;
    case TokenKind::INT16:
      output << "std::int16_t";
      return;
    case TokenKind::INT64:
      output << "std::int64_t";
      return;
    case TokenKind::UINT:
    case TokenKind::UINT32:
      output << "std::uint32_t";
      return;
    case TokenKind::UINT8:
      output << "std::uint8_t";
      return;
    case TokenKind::UINT16:
      output << "std::uint16_t";
      return;
    case TokenKind::UINT64:
      output << "std::uint64_t";
      return;
    case TokenKind::CHAR:
      output << "std::uint8_t";
      return;
    default:
      break;
    }
    if (type.name.last().kind == TokenKind::NULLPTR_TYPE) {
      output << "std::nullptr_t";
      return;
    }
    if (type.name.last().kind == TokenKind::EXPECTED) {
      output << (standard == CppStandard::Cpp23 ? "std::expected<"
                                                : "::nonstd::expected<");
      emitType(type.arguments[0]);
      output << ", ";
      emitType(type.arguments[1]);
      output << '>';
      return;
    }
    emitNamePath(type.name);
    if (!type.arguments.empty()) {
      output << '<';
      for (std::size_t index = 0; index < type.arguments.size(); ++index) {
        if (index > 0) {
          output << ", ";
        }
        emitType(type.arguments[index]);
      }
      output << '>';
    }
  }

  [[nodiscard]] static bool isInt32(const TypeRef &type) {
    return type.arrayExtents.empty() &&
           (type.name.last().kind == TokenKind::INT ||
            type.name.last().kind == TokenKind::INT32);
  }

  [[nodiscard]] static bool isExpectedVoid(const TypeRef &type) {
    return type.name.last().kind == TokenKind::EXPECTED &&
           type.arguments.size() == 2 &&
           type.arguments[0].name.last().kind == TokenKind::VOID;
  }

  [[nodiscard]] bool isGtiInternalUniqueOwner(const TypeRef &type) const {
    return semantics.compilerCapabilityType(type) ==
           CompilerCapabilityTypeKind::UniqueOwner;
  }

  [[nodiscard]] bool isGtiInternalStorage(const TypeRef &type) const {
    return semantics.compilerCapabilityType(type) ==
           CompilerCapabilityTypeKind::Storage;
  }

  [[nodiscard]] bool isGtiInternalTextView(const TypeRef &type) const {
    return semantics.compilerCapabilityType(type) ==
           CompilerCapabilityTypeKind::TextView;
  }

  [[nodiscard]] static bool isMoveOnlyOwner(const SemanticTypeTraits &traits) {
    return !traits.copyable && traits.movable;
  }

  [[nodiscard]] static bool isStorageIntrinsic(IntrinsicKind intrinsic) {
    return intrinsic == IntrinsicKind::StorageConstruct ||
           intrinsic == IntrinsicKind::StorageRead ||
           intrinsic == IntrinsicKind::StorageReadMut ||
           intrinsic == IntrinsicKind::StorageDestroy ||
           intrinsic == IntrinsicKind::StorageRelocate;
  }

