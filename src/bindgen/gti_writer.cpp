#include "gti/bindgen/gti_writer.h"

#include <sstream>

// Deterministic GTI emission. Non-function bindings keep header declaration
// order (C headers are already dependency-ordered); the extern "C" block
// follows them; the skip report closes the file so nothing the tool could
// not express disappears silently.

namespace lang::bindgen {
namespace {

void writeItem(const BindingItem &item, std::string_view indent,
               std::ostream &out) {
  switch (item.kind) {
  case BindingItemKind::Opaque:
    if (!item.reason.empty()) {
      out << indent << "// Layout not imported: " << item.reason << '\n';
    }
    out << indent << "[[c_opaque]] struct " << item.name << ";\n\n";
    return;
  case BindingItemKind::Record:
    out << indent << "[[c_abi]]\n"
        << indent << "struct " << item.name << " {\n";
    for (const BindingField &field : item.fields) {
      out << indent << "  mut " << field.spelling << ";\n";
    }
    out << indent << "};\n\n";
    return;
  case BindingItemKind::Enum: {
    // An anonymous C enum contributes only its constants; there is no type
    // name to alias.
    const bool anonymous = item.name.empty();
    if (!anonymous) {
      out << indent << "using " << item.name << " = int32_t;\n";
    }
    const std::string_view constantType =
        anonymous ? std::string_view("int32_t") : std::string_view(item.name);
    for (const BindingConstant &constant : item.constants) {
      out << indent << "constexpr " << constantType << ' ' << constant.name
          << " = " << (constant.value < 0 ? "int32_t(" : "") << constant.value
          << (constant.value < 0 ? ")" : "") << ";\n";
    }
    out << '\n';
    return;
  }
  case BindingItemKind::Alias:
    out << indent << "using " << item.name << " = " << item.aliasSpelling
        << ";\n\n";
    return;
  case BindingItemKind::Constant:
    // The negative wrapping matches the enum emission: a conversion keeps
    // the constant's type explicit instead of relying on literal typing.
    out << indent << "constexpr " << item.aliasSpelling << ' ' << item.name
        << " = " << (item.constantValue < 0 ? item.aliasSpelling + "(" : "")
        << item.constantValue << (item.constantValue < 0 ? ")" : "") << ";\n\n";
    return;
  case BindingItemKind::Callback: {
    if (item.synthesized) {
      out << indent
          << "// Synthesized name for an inline function-pointer shape.\n";
    }
    out << indent << "using " << item.name << " = (";
    for (std::size_t index = 0; index < item.parameters.size(); ++index) {
      out << (index != 0 ? ", " : "") << item.parameters[index].spelling;
    }
    out << ") -> " << item.resultSpelling << ";\n\n";
    return;
  }
  case BindingItemKind::Function:
  case BindingItemKind::Skipped:
    return;
  }
}

void writeFunction(const BindingItem &item, std::string_view indent,
                   std::ostream &out) {
  out << indent << "  " << item.resultSpelling << ' ' << item.name << '(';
  for (std::size_t index = 0; index < item.parameters.size(); ++index) {
    const BindingParameter &parameter = item.parameters[index];
    out << (index != 0 ? ", " : "") << parameter.spelling << ' '
        << parameter.name;
  }
  out << ");\n";
}

} // namespace

std::string writeGtiBindings(const BindingPlan &plan,
                             std::string_view headerName) {
  std::ostringstream out;
  out << "// Generated by `gti bindgen` from " << headerName
      << ". Do not edit.\n";
  out << "// Imported declarations: " << plan.importedCount()
      << "; skipped: " << plan.skippedCount() << ".\n\n";

  const bool namespaced = !plan.options.namespaceName.empty();
  const std::string_view indent = namespaced ? "  " : "";
  if (namespaced) {
    out << "namespace " << plan.options.namespaceName << " {\n\n";
  }

  bool hasFunctions = false;
  for (const BindingItem &item : plan.items) {
    if (item.kind == BindingItemKind::Function) {
      hasFunctions = true;
      continue;
    }
    writeItem(item, indent, out);
  }
  if (hasFunctions) {
    out << indent << "extern \"C\" {\n";
    for (const BindingItem &item : plan.items) {
      if (item.kind == BindingItemKind::Function) {
        writeFunction(item, indent, out);
      }
    }
    out << indent << "}\n";
  }
  if (namespaced) {
    out << "\n} // namespace " << plan.options.namespaceName << '\n';
  }

  bool wroteSkipBanner = false;
  for (const BindingItem &item : plan.items) {
    if (item.kind != BindingItemKind::Skipped) {
      continue;
    }
    if (!wroteSkipBanner) {
      out << "\n// Not imported:\n";
      wroteSkipBanner = true;
    }
    out << "//   " << (item.name.empty() ? "<unnamed>" : item.name) << " (";
    if (item.origin.file != 0 && item.origin.file <= plan.sourceFiles.size()) {
      out << plan.sourceFiles[item.origin.file - 1].path << ':'
          << item.origin.line;
    } else {
      out << "line " << item.origin.line;
    }
    out << "): " << item.reason << '\n';
  }
  return out.str();
}

} // namespace lang::bindgen
