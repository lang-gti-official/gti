import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  compileContentGraph,
  ContentContractError,
} from "../src/content/contract";
import type { ReferencePageRecord } from "../src/content/types";

interface Arguments {
  check: boolean;
  apiIndexPath?: string;
}

function parseArguments(argv: string[]): Arguments {
  const result: Arguments = { check: false };
  for (let index = 0; index < argv.length; ++index) {
    const argument = argv[index];
    if (argument === "--") {
      continue;
    }
    if (argument === "--check") {
      result.check = true;
      continue;
    }
    if (argument === "--api" && index + 1 < argv.length) {
      result.apiIndexPath = argv[++index];
      continue;
    }
    throw new Error(`Unknown or incomplete argument '${argument}'.`);
  }
  return result;
}

function importPath(fromDirectory: string, target: string): string {
  const relative = path.relative(fromDirectory, target).split(path.sep).join("/");
  return relative.startsWith(".") ? relative : `./${relative}`;
}

function generatedSource(
  pages: ReferencePageRecord[],
  outputPath: string,
  projectRoot: string,
): string {
  const lines = [
    "/* This file is generated by scripts/generate-content.ts. */",
    'import type { GeneratedReferencePage } from "../content/types";',
  ];
  pages.forEach((page, index) => {
    lines.push(
      `import Content${index} from ${JSON.stringify(
        importPath(
          path.dirname(outputPath),
          path.resolve(projectRoot, page.sourcePath),
        ),
      )};`,
    );
  });
  lines.push(
    "",
    "export const referencePages: readonly GeneratedReferencePage[] = [",
  );
  pages.forEach((page, index) => {
    const serialized = JSON.stringify(page, null, 2)
      .split("\n")
      .map((line, lineIndex) => (lineIndex === 0 ? line : `  ${line}`))
      .join("\n");
    lines.push(`  { ...${serialized}, Content: Content${index} },`);
  });
  lines.push("];", "");
  return lines.join("\n");
}

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");
const outputPath = path.join(projectRoot, "src/generated/reference-pages.ts");

try {
  const args = parseArguments(process.argv.slice(2));
  const defaultApiIndex = path.join(projectRoot, ".cache/documentation-index.json");
  const selectedApiIndex =
    args.apiIndexPath ?? process.env.GTI_DOCUMENTATION_INDEX;
  const apiIndexPath =
    selectedApiIndex ??
    (existsSync(defaultApiIndex) ? defaultApiIndex : undefined);
  const pages = compileContentGraph({
    projectRoot,
    contentRoot: "content",
    apiIndexPath,
  });
  if (!args.check) {
    mkdirSync(path.dirname(outputPath), { recursive: true });
    writeFileSync(
      outputPath,
      generatedSource(pages, outputPath, projectRoot),
      "utf8",
    );
  }
  console.log(
    `Validated ${pages.length} reference page${pages.length === 1 ? "" : "s"}.`,
  );
} catch (error) {
  if (error instanceof ContentContractError) {
    console.error(error.message);
  } else {
    console.error(error instanceof Error ? error.message : String(error));
  }
  process.exitCode = 1;
}
