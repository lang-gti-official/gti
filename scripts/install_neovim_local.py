#!/usr/bin/env python3
"""Install a Mac-local GTI toolchain for terminal commands and Neovim."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import pathlib
import platform
import re
import shlex
import shutil
import subprocess
import tempfile


ROOT = pathlib.Path(__file__).resolve().parent.parent
TOOLS = ("gti", "gti_lsp")
CANONICAL = "https://github.com/lang-gti-official/gti.git"


def preview_source(root, dry_run=False):
    """Pin canonical preview in a persistent detached worktree; never reset source."""
    def git(*arguments):
        return run(["git", "-C", root, *arguments], capture=True).stdout.strip()

    # Resolve the fixed canonical repository directly. Local remote aliases,
    # SSH/HTTPS spelling and push URLs cannot redirect preview installation.
    fields = git("ls-remote", "--exit-code", CANONICAL, "refs/heads/preview").split()
    if len(fields) != 2 or fields[1] != "refs/heads/preview" or not re.fullmatch(r"[0-9a-f]{40}", fields[0]):
        raise ValueError("canonical preview has no published commit")
    head = fields[0]
    common = pathlib.Path(git("rev-parse", "--path-format=absolute", "--git-common-dir")).resolve()
    destination = common.parent.parent / "gti-preview-installs" / head
    print(f"Selected preview source: {head}\nPreview checkout: {destination}")
    print("Preview can include PRs whose full validation and review are still pending.")
    if dry_run:
        print("Dry run: no fetch, checkout, build, configuration or installation performed.")
        return None, head
    git("fetch", CANONICAL, head)
    if git("rev-parse", "FETCH_HEAD") != head:
        raise ValueError("preview fetch did not resolve the selected commit")
    manifest = json.loads(git("show", head + ":.gti-preview.json"))
    if manifest.get("schema") != 1 or not isinstance(manifest.get("features"), list):
        raise ValueError("preview source has no valid inclusion manifest")
    if destination.exists():
        selected = lambda *args: run(["git", "-C", destination, *args], capture=True).stdout.strip()
        attached = subprocess.run(["git", "-C", str(destination), "symbolic-ref", "-q", "HEAD"],
                                  capture_output=True, text=True, check=False)
        if (destination.is_symlink() or selected("rev-parse", "--show-toplevel") != str(destination)
                or selected("rev-parse", "HEAD") != head
                or selected("status", "--porcelain") or attached.returncode != 1):
            raise ValueError("existing preview checkout changed; preserve it and resolve manually")
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        git("worktree", "add", "--detach", str(destination), head)
    return destination, head


def default_jobs():
    return max(1, os.cpu_count() or 1)


def run(command, *, env=None, cwd=None, capture=False):
    print("+ " + shlex.join(str(part) for part in command), flush=True)
    return subprocess.run([str(part) for part in command], check=True,
                          env=env, cwd=cwd, text=True, capture_output=capture)


def lazy_config(root):
    # JSON string spelling is also Lua string spelling for ordinary paths;
    # reject controls rather than emitting JSON-only Unicode escapes.
    if any(ord(character) < 32 for character in str(root)):
        raise ValueError("the checkout path must not contain control characters")
    quoted = json.dumps(str(root), ensure_ascii=False)
    return (
        "-- Generated by GTI's local installer. Re-run it after updating GTI.\n"
        f"local root = {quoted}\n"
        "return {{\n"
        '  dir = root, name = "gti", lazy = false, version = false, build = false,\n'
        "  init = function()\n"
        '    vim.g.gti_channel = "stable"\n'
        '    vim.env.GTI_PATH = root .. "/toolchain/bin/gti"\n'
        '    vim.env.GTI_LSP_PATH = root .. "/toolchain/bin/gti_lsp"\n'
        '    vim.env.GTI_TREE_SITTER_PATH = root .. "/toolchain/share/gti/parser/gti.so"\n'
        "  end,\n"
        "}}\n"
    )


def check_config(path, content, replace):
    if path.is_symlink():
        raise ValueError(f"refusing to replace a symlink: {path}")
    if path.exists() and (not path.is_file() or
                          (path.read_text() != content and not replace)):
        raise ValueError(f"{path} already exists; inspect it, then use "
                         "--replace-config to replace it with a saved backup")


def write_config(path, content, replace):
    check_config(path, content, replace)
    if path.exists() and path.read_text() == content:
        return None
    path.parent.mkdir(parents=True, exist_ok=True)
    backup = None
    if path.exists():
        descriptor, name = tempfile.mkstemp(prefix=path.name + ".backup-",
                                          suffix=".bak", dir=path.parent)
        os.close(descriptor)
        backup = pathlib.Path(name)
        shutil.copy2(path, backup)
    descriptor, name = tempfile.mkstemp(prefix=".gti-config-", suffix=".tmp",
                                      dir=path.parent)
    temporary = pathlib.Path(name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as output:
            output.write(content)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)
    return backup


def check_commands(directory, toolchain, replace):
    if directory.exists() and not directory.is_dir():
        raise ValueError(f"terminal command directory is not a directory: {directory}")
    for tool in TOOLS:
        destination = directory / tool
        target = toolchain / "bin" / tool
        if destination.is_symlink() and destination.resolve() == target.resolve():
            continue
        if destination.exists() or destination.is_symlink():
            if destination.is_dir() or not replace:
                raise ValueError(f"{destination} already exists; inspect it, then use "
                                 "--replace-bin to replace it with a saved backup")


def activate_commands(directory, toolchain, replace):
    check_commands(directory, toolchain, replace)
    directory.mkdir(parents=True, exist_ok=True)
    changed = []
    # Stage both links first and roll back either command if publication fails.
    with tempfile.TemporaryDirectory(prefix=".gti-links-", dir=directory) as scratch:
        links = pathlib.Path(scratch)
        for tool in TOOLS:
            (links / tool).symlink_to(toolchain / "bin" / tool)
        try:
            for tool in TOOLS:
                destination = directory / tool
                if destination.is_symlink() and destination.resolve() == (toolchain / "bin" / tool).resolve():
                    continue
                backup = None
                if destination.exists() or destination.is_symlink():
                    descriptor, name = tempfile.mkstemp(prefix=tool + ".backup-",
                                                      suffix=".bak", dir=directory)
                    os.close(descriptor)
                    backup = pathlib.Path(name)
                    try:
                        os.replace(destination, backup)
                    except OSError:
                        backup.unlink()
                        raise
                changed.append((destination, backup))
                os.replace(links / tool, destination)
        except OSError:
            for destination, backup in reversed(changed):
                if backup is not None:
                    os.replace(backup, destination)
                else:
                    destination.unlink(missing_ok=True)
            raise
    return [backup for _, backup in changed if backup is not None]


def validate_installed_toolchain(toolchain):
    required = ("share/gti/VERSION", "share/gti/parser/gti.so",
                "share/gti/stdlib/prelude.gti", "lib/libgti_runtime.a")
    for relative in required:
        if not (toolchain / relative).is_file():
            raise ValueError(f"installed toolchain is missing {relative}; rebuild before activation")
    version = (toolchain / "share/gti/VERSION").read_text().strip()
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError("installed toolchain has an invalid VERSION")
    for tool in TOOLS:
        executable = toolchain / "bin" / tool
        if not executable.is_file() or not os.access(executable, os.X_OK):
            raise ValueError(f"installed toolchain is missing executable {executable}")
        result = run([executable, "--version"], capture=True)
        if result.stdout.strip() != f"{tool} {version}":
            raise ValueError(f"{tool} does not match installed toolchain VERSION {version}")
    return version


def cache_values(build):
    cache = build / "CMakeCache.txt"
    if not cache.exists():
        return None
    return dict((match.group(1), match.group(2))
                for line in cache.read_text().splitlines()
                if (match := re.match(r"([^/#][^:]*):[^=]+=(.*)", line)))


def supported_llvm(directory):
    version_file = directory / "LLVMConfigVersion.cmake"
    if not (directory / "LLVMConfig.cmake").is_file() or not version_file.is_file():
        return False
    version = re.search(r'set\(PACKAGE_VERSION\s+"(\d+)\.', version_file.read_text())
    return version is not None and int(version.group(1)) >= 18


def discover_llvm():
    if not shutil.which("brew"):
        return None
    for formula in ("llvm", "llvm@23", "llvm@22", "llvm@21", "llvm@20", "llvm@19",
                    "llvm@18"):
        result = subprocess.run(["brew", "--prefix", formula], capture_output=True, text=True)
        if result.returncode != 0:
            continue
        prefix = pathlib.Path(result.stdout.strip())
        candidate = prefix / "lib/cmake/llvm"
        if supported_llvm(candidate):
            return candidate.resolve()
        # Homebrew can retain a supported version after upgrading the opt alias.
        # Ask brew for its Cellar rather than assuming Apple Silicon's prefix.
        cellar = subprocess.run(["brew", "--cellar", formula], capture_output=True, text=True)
        if cellar.returncode == 0 and cellar.stdout.strip():
            candidates = sorted(pathlib.Path(cellar.stdout.strip()).glob("*/lib/cmake/llvm"),
                                reverse=True)
            for candidate in candidates:
                if supported_llvm(candidate):
                    return candidate.resolve()
    return None


def configure_command(build, llvm_dir):
    values = cache_values(build)
    if values is not None:
        if pathlib.Path(values.get("CMAKE_HOME_DIRECTORY", "")).resolve() != ROOT:
            raise ValueError("build directory belongs to a different source checkout")
        if values.get("CMAKE_BUILD_TYPE") != "Release" or values.get("GTI_BUILD_LSP") != "ON":
            raise ValueError("existing build must be Release with GTI_BUILD_LSP=ON; "
                             "use a fresh --build-dir")
        # A selected dependency may change after a package-manager upgrade.
        # CMake refreshes include/link inputs and rebuilds affected targets;
        # keep the source, optimized-build and generator safety checks above.
        # Refresh install rules after updates, without switching the generator.
        command = ["cmake", "-S", ROOT, "-B", build]
    else:
        command = ["cmake", "-S", ROOT, "-B", build, "-G", "Ninja",
                   "-DCMAKE_BUILD_TYPE=Release", "-DGTI_BUILD_LSP=ON",
                   "-DBUILD_TESTING=OFF", "-DGTI_RELEASE_BUILD=OFF",
                   "-DGTI_BUNDLE_LLVM=OFF"]
    if llvm_dir:
        command.append(f"-DLLVM_DIR={llvm_dir}")
        clang_dir = llvm_dir.parent / "clang"
        if (clang_dir / "ClangConfig.cmake").is_file():
            command.append(f"-DClang_DIR={clang_dir}")
    return command


def main():
    global ROOT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=pathlib.Path,
                        help="build directory (default: selected source's out/neovim-local-build)")
    parser.add_argument("--preview", action="store_true",
                        help="build canonical preview in an isolated checkout and activate it")
    parser.add_argument("--llvm-dir", type=pathlib.Path,
                        help="directory containing LLVMConfig.cmake")
    parser.add_argument("--config", type=pathlib.Path,
                        help="Lazy spec file (default: Neovim's lua/plugins/gti.lua)")
    parser.add_argument("--replace-config", action="store_true",
                        help="back up and replace an existing different Lazy spec")
    parser.add_argument("--bin-dir", type=pathlib.Path,
                        default=pathlib.Path.home() / ".local/bin",
                        help="terminal command directory (default: ~/.local/bin)")
    parser.add_argument("--replace-bin", action="store_true",
                        help="back up and replace existing different terminal commands")
    parser.add_argument("--no-terminal", action="store_true",
                        help="configure Neovim without installing terminal commands")
    parser.add_argument("--activate-only", action="store_true",
                        help="validate and activate the existing toolchain without rebuilding")
    parser.add_argument("--jobs", type=int, default=default_jobs(),
                        help="parallel build jobs (default: all detected CPUs)")
    parser.add_argument("--dry-run", action="store_true",
                        help="inspect prerequisites and destinations without writing")
    args = parser.parse_args()
    if platform.system() != "Darwin":
        parser.error("this installer is for macOS")
    if args.jobs < 1:
        parser.error("--jobs must be a positive integer")
    if args.preview:
        if args.activate_only:
            parser.error("--preview selects and builds source; it cannot be combined with --activate-only")
        selected, head = preview_source(ROOT, args.dry_run)
        if selected is None:
            return
        ROOT = selected
        print(f"Installing CLI, LSP and parser from preview commit {head}")
    prerequisites = ("nvim",) if args.activate_only else ("cmake", "nvim", "tar", "c++")
    for executable in prerequisites:
        if not shutil.which(executable):
            parser.error(f"{executable} is required; see README's local Neovim setup")
    nvim = ["nvim", "--headless", "-u", "NONE", "-i", "NONE", "-n"]
    probe = run(nvim + ["-l", ROOT / "scripts/install_neovim_local.lua", "probe"], capture=True)
    configuration = args.config or pathlib.Path(json.loads(probe.stdout)) / "lua/plugins/gti.lua"
    configuration = configuration.expanduser().absolute()
    content = lazy_config(ROOT)
    check_config(configuration, content, args.replace_config)
    toolchain = ROOT / "toolchain"
    bin_dir = args.bin_dir.expanduser().absolute()
    if not args.no_terminal:
        if bin_dir.resolve() == toolchain.resolve() or bin_dir.resolve().is_relative_to(toolchain.resolve()):
            parser.error("--bin-dir must not be inside the installed toolchain")
        check_commands(bin_dir, toolchain, args.replace_bin)
    if toolchain.is_symlink():
        parser.error("refusing to replace a symlinked toolchain directory")
    if (ROOT / ".gti-toolchain-backup").exists():
        parser.error("a previous installer backup exists; recover it before reinstalling")
    if args.activate_only:
        version = validate_installed_toolchain(toolchain)
        print(f"Existing toolchain: {toolchain} (GTI {version})\nLazy config: {configuration}")
        if not args.no_terminal:
            print(f"Terminal commands: {bin_dir}")
        if args.dry_run:
            return
        finish_activation(configuration, content, args.replace_config,
                          bin_dir, toolchain, args.replace_bin, args.no_terminal, version)
        return
    build = (args.build_dir or ROOT / "out/neovim-local-build").expanduser().resolve()
    if build == ROOT or ROOT.is_relative_to(build):
        parser.error("--build-dir must not be the source checkout or its parent")
    if build == ROOT / "toolchain" or build.is_relative_to(ROOT / "toolchain"):
        parser.error("--build-dir must not be inside the installed toolchain")
    llvm_dir = args.llvm_dir or os.environ.get("LLVM_DIR")
    if llvm_dir:
        llvm_dir = pathlib.Path(llvm_dir).expanduser().resolve()
        if not supported_llvm(llvm_dir):
            parser.error("--llvm-dir/LLVM_DIR must select LLVM 18 or newer")
    else:
        values = cache_values(build)
        cached = (pathlib.Path(values["LLVM_DIR"])
                  if values and values.get("LLVM_DIR") else None)
        # Resolve a moving Homebrew opt alias on every configuration, including
        # an existing cache, and select its matching Clang package as well.
        llvm_dir = (cached.resolve() if cached and supported_llvm(cached)
                    else discover_llvm())
        if llvm_dir is None:
            parser.error("no LLVM 18 or newer found; install a compatible "
                         "LLVM (including libclang), for example brew install llvm, "
                         "then pass --llvm-dir. To restore commands from an already "
                         "installed toolchain without rebuilding, use --activate-only")
    configure = configure_command(build, llvm_dir)
    if "-G" in configure and not shutil.which("ninja"):
        parser.error("Ninja is required for a fresh build")
    print(f"Build: {build}\nToolchain: {ROOT / 'toolchain'}\nLazy config: {configuration}")
    if not args.no_terminal:
        print(f"Terminal commands: {bin_dir}")
    print(f"Parallel build jobs: {args.jobs}")
    print("macOS runtime libraries will be bundled; build prerequisites remain external.")
    if args.dry_run:
        return
    if configure:
        run(configure)
    run(["python3", ROOT / "scripts/build_window.py", "--kind", "build", "--",
         "cmake", "--build", build, "--parallel", str(args.jobs),
         "--target", "gti", "gti_lsp", "gti_tree_sitter"])
    version = (ROOT / "VERSION").read_text().strip()
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError("invalid VERSION")
    machine = platform.machine().lower()
    architecture = {"arm64": "arm64", "aarch64": "arm64", "x86_64": "x64"}.get(machine)
    if architecture is None:
        raise ValueError(f"unsupported Mac architecture: {machine}")
    native_platform = "darwin-" + architecture
    # Stage beside the build, then use the *same* checksum/extraction/activation
    # implementation as release downloads. Neither this path nor the editor
    # smoke test contacts a release server or runs the user's Neovim config.
    with tempfile.TemporaryDirectory(prefix="gti-neovim-local-") as directory:
        scratch = pathlib.Path(directory)
        stage = scratch / "stage"
        run(["cmake", "--install", build, "--prefix", stage, "--component", "gti_toolchain"])
        if args.preview:
            (stage / "share/gti/PREVIEW_SOURCE").write_text(head + "\n")
        archive = scratch / f"gti-v{version}-{native_platform}.tar.gz"
        run(["cmake", "-E", "tar", "czf", archive, "."], cwd=stage)
        checksum = pathlib.Path(str(archive) + ".sha256")
        with archive.open("rb") as source:
            hasher = hashlib.sha256()
            for chunk in iter(lambda: source.read(1024 * 1024), b""):
                hasher.update(chunk)
            digest = hasher.hexdigest()
        checksum.write_text(f"{digest}  {archive.name}\n")
        environment = os.environ.copy()
        for key in ("GTI_STDLIB_PATH", "GTI_RUNTIME_INCLUDE", "GTI_RUNTIME_LIBRARY",
                    "GTI_PATH", "GTI_LSP_PATH", "GTI_TREE_SITTER_PATH"):
            environment.pop(key, None)
        environment.update(GTI_TEST_REPOSITORY=str(ROOT), GTI_TEST_ARCHIVE=str(archive),
                           GTI_TEST_CHECKSUM=str(checksum), GTI_TEST_PLATFORM=native_platform)
        run([*nvim, "-l", ROOT / "tests/nvim_plugin_smoke_test.lua"],
            env=environment)
        run(nvim + ["-l", ROOT / "scripts/install_neovim_local.lua"], env=environment)
    validate_installed_toolchain(toolchain)
    finish_activation(configuration, content, args.replace_config,
                      bin_dir, toolchain, args.replace_bin, args.no_terminal, version)
    if args.preview:
        print(f"Installed preview GTI {version} from {head}")


def finish_activation(configuration, content, replace_config, bin_dir,
                      toolchain, replace_bin, no_terminal, version):
    if not no_terminal:
        for backup in activate_commands(bin_dir, toolchain, replace_bin):
            print(f"Previous terminal command saved to: {backup}")
        print(f"Terminal commands installed in: {bin_dir}")
        visible = shutil.which("gti")
        if visible is None or pathlib.Path(visible).resolve() != (toolchain / "bin/gti").resolve():
            print("Put the terminal command directory first in PATH:")
            print(f"export PATH={shlex.quote(str(bin_dir))}:\"$PATH\"")
        print("Run rehash in existing zsh sessions, then gti --version.")
    backup = write_config(configuration, content, replace_config)
    if backup:
        print(f"Previous Lazy configuration saved to: {backup}")
    print(f"Installed GTI {version}. Restart Neovim, run :Lazy sync, then :GTIInfo.")
    print("Re-run this script after pulling changes. Local mode does not download releases.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        raise SystemExit(str(error)) from error
